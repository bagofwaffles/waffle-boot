/*
 * The installer's write engine (wiki/Installer-Reference.md): the installer carries a
 * waffle-boot slot image in its own stream and, once the runner
 * (src/testos/opxy_testos_installer.c) has a hold on the unit's key for it,
 * writes it to the slot the selector does not name. Two forms:
 *
 *   trial   the image, a record whose crc32 is wrong, byte 0 of slot k's start
 *           log 0xFD (a trial pending, S-02.095), and a selector that names
 *           slot k unverified: {0x00, 0xFE} for slot 0, the erased
 *           {0xFF, 0xFF} for slot 1. The first stage's check fails, it writes
 *           {other, 0x01} and boots slot k once (S-02.022, S-02.023); slot k's
 *           front marks that start, 0xFD to 0xFC (started). The next reset,
 *           the trial start's own restart into the OS among them, boots the
 *           other.
 *   commit  after a trial start that reached the boot menu: the same bytes
 *           still in slot k, its trial entry started and the boot menu's
 *           mark after it (byte 0 0xF0, S-02.095), the record made right,
 *           the selector {k, 0x00}. The next boot checks, passes and trusts
 *           slot k.
 *
 * Neither form writes anything unless the runner found the carried image
 * whole (its CRC-32, its stream, its descriptor and its front's pin,
 * inst_image_check()).
 *
 * Every write goes through a gate that allows slot k's sectors, its record's
 * sector and, at the end, the selector's; once the upgrade is done, of slot
 * k's sectors only byte 0 of its last. Nothing below the selector can be
 * reached, nor the slot the selector names, so a power cut at any point leaves
 * a selected slot that boots: the first stage is never touched, and the
 * selector stays as it was until the read-back has passed.
 *
 * It is not in the bootloader: S-02.050 and S-02.090 hold for waffle-boot,
 * and this runs as an OS, started by the bootloader the unit has.
 *
 * On the OP-1F a trial is refused when its target is the last slot whose
 * image is not a waffle-boot stream (S-02.108, inst_keeps_factory()): the
 * bootloader the unit came with stays in one slot. A survey build refuses every form
 * but the status, its gate refuses every erase and program, and its link
 * wraps the flash driver's erase and program so that nothing in the image
 * reaches them (__wrap_wb_spiflash_erase(), the Makefile's --wrap).
 */
