#define TRIAL_CRC_XOR 0xFFFFFFFFu	/* the trial mark: every CRC bit inverted (S-02.016) */
_Static_assert(TRIAL_CRC_XOR == 0xFFFFFFFFu, "trial_crc_flip inverts every crc bit");


/* Generated by tools/installer_image.py from the image the build made. */
extern const uint8_t opxy_install_image[];
extern const uint32_t opxy_install_len;
extern const uint32_t opxy_install_crc;

struct gate {
	struct wb_spiflash *flash;
	uint32_t slot;		/* slot k's base */
	uint32_t record;	/* its record's sector */
	bool armed;		/* slot k is known: nothing is allowed before */
	bool selector_open;
	bool at_selector;	/* the writer got as far as the selector */
	uint32_t refused;
	bool trial_crc;		/* slot k's record crc is inverted on the way */
	bool log_only;		/* of slot k and its record, byte 0 of its log alone */
};

/* Slot t's last sector: its start log (S-02.095), or a breadcrumb build's marks. */
static uint32_t last_sector(unsigned t)
{
	return s02_slot_base(t) + S02_SLOT_CAPACITY - S02_SECTOR_SIZE;
}

/*
 * A trial's record holds the crc inverted (TRIAL_CRC_XOR) from its first
 * program: with trial_crc set, the gate inverts the 4 crc bytes of slot k's
 * record in every program and every read, so the upgrade writes and reads
 * back the right crc while the flash never holds it. A cut before the
 * selector then leaves slot k bad, not good and untried.
 */
static void trial_crc_flip(const struct gate *g, uint32_t off, uint8_t *buf, uint32_t len)
{
	for (uint32_t i = 0; i < 4u; i++) {
		const uint32_t at = g->record + i;

		if (at >= off && at - off < len)
			buf[at - off] = (uint8_t)~buf[at - off];
	}
}

static bool trial_crc_in(const struct gate *g, uint32_t off, uint32_t len)
{
	return g->trial_crc && off < g->record + 4u && (uint64_t)off + len > g->record;
}

static bool gate_allows(const struct gate *g, uint32_t off, uint32_t len)
{
	if (!g->armed || (uint64_t)off + len > S02_FLASH_SIZE)
		return false;
	if (g->log_only) {
		if (off == g->slot + S02_SLOT_CAPACITY - S02_SECTOR_SIZE && len == 1u)
			return true;
	} else if (off >= g->slot && off + len <= g->slot + S02_SLOT_CAPACITY) {
		return true;
	} else if (off >= g->record && off + len <= g->record + S02_SECTOR_SIZE) {
		return true;
	}
	return g->selector_open && off >= S02_SELECTOR_OFF &&
	       off + len <= S02_SELECTOR_OFF + S02_SECTOR_SIZE;
}

static int gate_read(void *ctx, uint32_t off, uint8_t *buf, uint32_t len)
{
	const struct gate *g = ctx;
	const int rc = wb_spiflash_read(g->flash, off, buf, len);

	if (rc == 0 && trial_crc_in(g, off, len))
		trial_crc_flip(g, off, buf, len);
	return rc;
}

