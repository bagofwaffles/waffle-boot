/* Set once a failed selector step leaves a selector the settling does
 * not write (settle_on_0()): every later trial or commit is refused until
 * a restart. */
static bool held_until_restart;

/* The selector's index programmed to 0x00 and read back, programmed once
 * more when it does not read 0x00; true when it then reads 0x00. */
static bool index_to_0(const struct s02_env *env)
{
	static const uint8_t index_0 = 0x00u;
	struct s02_selector sel;

	if (env->flash->program(env->flash->ctx, S02_SELECTOR_OFF, &index_0, 1u) == 0 &&
	    s02_read_selector(env, &sel) == S02_OK && sel.index == 0x00u)
		return true;
	(void)env->flash->program(env->flash->ctx, S02_SELECTOR_OFF, &index_0, 1u);
	return s02_read_selector(env, &sel) == S02_OK && sel.index == 0x00u;
}

/*
 * S-02.102 item 6: a selector step for slot 1 that failed settles the
 * selector back on slot 0, the good running slot, ending {0x00, 0x01}, by
 * programs alone. Nothing is written where it reads so already. Where
 * `verified` has bit 0 set: the index to 0x00, read back, then `verified`
 * to 0x01. A program only clears bits, so cut short it leaves the index it
 * had or fewer of its bits, and `verified` with bit 0 still set: the
 * settling creates no selector that names slot 1 where the failed step's
 * did not. Where `verified` has bit 0 clear, or the selector cannot be
 * read, nothing is written: an erase there could name slot 1, so the
 * selector stays as it is and no slot write is made until a restart lets
 * the first stage settle it. False then. Results are not reported
 * otherwise: the caller's error stands, and the reply reads the selector
 * again.
 */
static bool settle_on_0(const struct s02_env *env)
{
	static const uint8_t verified_1 = 0x01u;
	struct s02_selector sel;

	if (s02_read_selector(env, &sel) != S02_OK || (sel.verified & 0x01u) == 0u) {
		held_until_restart = true;
		return false;
	}
	if (sel.index == 0x00u && sel.verified == 0x01u)
		return true;
	if (sel.index != 0x00u && !index_to_0(env))
		return true;
	if (sel.verified != 0x01u)
		(void)env->flash->program(env->flash->ctx, S02_SELECTOR_OFF + 1u,
					  &verified_1, 1u);
	return true;
}

/* S-02.042-.047 as they stand; the gate stops the upgrade at the selector,
 * and the record it writes holds the trial's crc. */
static int trial_upgrade(const struct s02_env *env, struct gate *g, unsigned *target)
{
	int rc;

	g->trial_crc = true;
	rc = s02_slot_upgrade(env, true, opxy_install_image, opxy_install_len, target);
	g->trial_crc = false;
	return rc;
}

/*
 * The trial: the record with the wrong crc, already in place (the upgrade
 * wrote it through trial_crc), read back; then a selector that names slot t
 * unverified, chosen so that a power cut here or in the first stage's own
 * selector write on the trial start (S-02.022) does not trust slot t:
 *   t = 0  the erase, verified 0xFE, then index 0x00, each read back. A torn
 *          erase keeps the old nonzero index, 0xFE is one bit from erased and
 *          never tears to 0x01, and the first stage's write {0x01, 0x01}
 *          only tears to a nonzero index.
 *   t = 1  the erase alone, read back {0xFF, 0xFF}: an index that names
 *          slot 1 (S-02.011), a verified byte that takes the check path.
 *          Programming nothing adds no tear, but two remain that no value
 *          written here closes: this erase of {0x00, 0x01}, and the first
 *          stage's program of {0x00, 0x01}, can each read {nonzero, 0x01}.
 * On a failure (a fault, not a cut) the selector is left as the steps allow:
 *   t = 1  after the erase it can read {odd, 0x01}, trusting slot t, so it is
 *          settled back on slot 0, the good running slot, to {0x00, 0x01}
 *          by programs alone (settle_on_0()): no first stage then has a
 *          selector write of its own to make, which cut short could read
 *          {0x01, 0x01}. A selector whose `verified` has bit 0 clear is left
 *          as it is, and slot writes are refused until a restart. The
 *          original error is returned.
 *   t = 0  nothing more is written. A failed erase from {nonzero, 0x01}
 *          keeps a nonzero index, slot 1, the good one; a failed 0xFE
 *          program leaves {0xFF, 0xFE or 0xFF}, slot 1 checked; a failed
 *          index program leaves verified 0xFE with a nonzero index (slot 1
 *          checked) or 0x00, the trial selector itself. No program can bring
 *          a cleared index bit back, so none can do better.
 * Before the selector, as recovery's trial write does (S-02.084, S-02.095):
 * byte 0 of slot t's last sector, which the upgrade erased (S-02.045),
 * programmed to 0xFD, a trial pending, and the sector read back; a failure
 * there writes nothing of the selector. From here the gate allows of slot t
 * that one byte alone.
 */
static int trial_finish(const struct s02_env *env, struct gate *g, unsigned t)
{
	static const uint8_t ver_fe = 0xFEu, index_0 = 0x00u, pending = 0xFDu;
	struct s02_record back;
	int rc = s02_read_record(env, t, &back);

	g->log_only = true;
	if (rc != S02_OK)
		return rc;
	if (back.crc32 != (opxy_install_crc ^ TRIAL_CRC_XOR) ||
	    back.length != opxy_install_len || !s02_tag_ok(back.tag))
		return S02_ERR_VERIFY;
	if (env->flash->program(env->flash->ctx, last_sector(t), &pending, 1u) != 0)
		return S02_ERR_IO;
	rc = trial_entry_pending(env, t);
	if (rc != S02_OK)
		return rc;
	g->selector_open = true;
	if (t != 0u) {
		rc = env->flash->erase(env->flash->ctx, S02_SELECTOR_OFF) != 0 ?
			     S02_ERR_IO : selector_is(env, 0xFFu, 0xFFu);
		if (rc != S02_OK)
			(void)settle_on_0(env);
		return rc;
	}
	if (env->flash->erase(env->flash->ctx, S02_SELECTOR_OFF) != 0)
		return S02_ERR_IO;
	rc = selector_is(env, 0xFFu, 0xFFu);
	if (rc != S02_OK)
		return rc;
	if (env->flash->program(env->flash->ctx, S02_SELECTOR_OFF + 1u, &ver_fe, 1u) != 0)
		return S02_ERR_IO;
	rc = selector_is(env, 0xFFu, ver_fe);
	if (rc != S02_OK)
		return rc;
	if (env->flash->program(env->flash->ctx, S02_SELECTOR_OFF, &index_0, 1u) != 0)
		return S02_ERR_IO;
	return selector_is(env, index_0, ver_fe);
}

/* What slot t holds, as far as this image goes; no bytes of it leave here. */
static uint8_t slot_state(const struct s02_env *env, unsigned t)
{
	struct s02_record r;
	bool good = false;
	uint8_t st = 0u;

	if (s02_check_slot(env, t, &good) == S02_OK && good)
		st |= OPXY_INSTALL_SLOT_GOOD;
	if (s02_read_record(env, t, &r) == S02_OK && r.length == opxy_install_len &&
	    s02_tag_ok(r.tag) && slot_is_image(env, t) == S02_OK) {
		if (r.crc32 == opxy_install_crc)
			st |= OPXY_INSTALL_SLOT_COMMITTED;
		else if (r.crc32 == (opxy_install_crc ^ TRIAL_CRC_XOR))
			st |= OPXY_INSTALL_SLOT_TRIAL;
	}
	/* A tried slot's trial entry (S-02.095): byte 0 of its log. */
	if ((st & OPXY_INSTALL_SLOT_TRIAL) != 0u) {
		uint8_t b = 0xFFu;

		if (env->flash->read(env->flash->ctx, last_sector(t), &b, 1u) != 0)
			b = 0xFFu;
		/* As the front reads it: pending 0xFD alone, started 0, spent 1, 0
		 * in any other byte; 0xFF no entry; anything else odd. */
		if (b == 0xFDu)
			st |= OPXY_INSTALL_SLOT_PENDING;
		else if ((b & 0x03u) == 0u)
			st |= OPXY_INSTALL_SLOT_STARTED;
		else if ((b & 0x03u) == 1u)
			st |= OPXY_INSTALL_SLOT_SPENT;
		else if (b != 0xFFu)
			st |= OPXY_INSTALL_SLOT_ODD;
		/* the trial's main image reached the boot menu: entry 1 finished
		 * after the front's mark (opxy_trial_reached()) */
		if (b == OPXY_TRIAL_REACHED_BYTE)
			st |= OPXY_INSTALL_SLOT_REACHED;
	}
	return st;
}

/*
 * What S-02.065's restore would do on a boot of waffle-boot: nothing when the
 * mirror is not valid or equals the record, and a write of the record when not.
 * The answer alone leaves here.
 */
static uint8_t mirror_state(const struct s02_env *env)
{
	/* the device's record size (S-02.018, S-18.030): 0x34 or 0x28 */
	const uint32_t size = s02_meta_size(env);
	uint8_t mirror[S02_MIRROR_SIZE];
	uint8_t rec[S02_META_SIZE];

	if (env->flash->read(env->flash->ctx, S02_MIRROR_OFF, mirror, 2u * size) != 0 ||
	    env->flash->read(env->flash->ctx, S02_META_OFF, rec, size) != 0)
		return OPXY_INSTALL_MIRROR_UNREAD;
	if (!s02_mirror_valid_n(mirror, size))
		return OPXY_INSTALL_MIRROR_INVALID;
	return memcmp(mirror, rec, size) == 0 ? OPXY_INSTALL_MIRROR_SAME :
						OPXY_INSTALL_MIRROR_DIFFERS;
}

static uint32_t crc_of(uint32_t crc, const uint8_t *p, size_t n)
{
	return wire_crc32(crc, p, (uint32_t)n);
}

/* Bit k set when slot k's image is a waffle-boot stream. */
static uint8_t streams_of(const struct s02_env *env)
{
	uint8_t bits = 0u;

	for (unsigned k = 0; k < 2u; k++)
		if (s02_stream_is_waffle(env->flash->read, env->flash->ctx, s02_slot_base(k),
					 S02_SLOT_CAPACITY, crc_of))
			bits = (uint8_t)(bits | 1u << k);
	return bits;
}

/*
 * The start log of slot s (S-02.095), summed up into out (OPXY_INSTALL_LOG
 * bytes, waffle/testos.h); only for a slot that holds this image.
 */
static void log_summary(const struct s02_env *env, unsigned s, uint8_t *out)
{
	const uint32_t at = last_sector(s);
	uint32_t used = 0, unfinished = 0, last = 0;
	uint8_t state = OPXY_INSTALL_LOG_FULL;
	bool free_seen = false;

	out[0] = 1u;
	out[1] = (uint8_t)s;
	if (opxy_install_len > S02_SLOT_CAPACITY - S02_SECTOR_SIZE)
		state = OPXY_INSTALL_LOG_NONE;	/* the image reaches the sector */
	for (uint32_t off = 0; state == OPXY_INSTALL_LOG_FULL && off < S02_SECTOR_SIZE;
	     off += env->scratch_len) {
		const uint32_t k = S02_SECTOR_SIZE - off < env->scratch_len ?
					   S02_SECTOR_SIZE - off : env->scratch_len;

		if (env->flash->read(env->flash->ctx, at + off, env->scratch, k) != 0) {
			state = OPXY_INSTALL_LOG_UNREAD;
			break;
		}
		for (uint32_t i = 0; i < 4u * k && state == OPXY_INSTALL_LOG_FULL; i++) {
			const unsigned v = ((unsigned)env->scratch[i / 4u] >> (2u * (i % 4u))) & 3u;

			if (v == 3u) {
				free_seen = true;
			} else if (free_seen || v == 1u) {
				state = OPXY_INSTALL_LOG_ODD;	/* a used entry after a free one, or 01 */
			} else {
				used++;
				unfinished = v == 2u ? unfinished + 1u : 0u;
				last = (last << 2 | v) & 0xFFFFu;
			}
		}
	}
	if (state == OPXY_INSTALL_LOG_FULL && free_seen)
		state = OPXY_INSTALL_LOG_OK;
	out[2] = state;
	out[3] = (uint8_t)used;
	out[4] = (uint8_t)(used >> 8);
	out[5] = (uint8_t)unfinished;
	out[6] = (uint8_t)(unfinished >> 8);
	out[7] = (uint8_t)last;
	out[8] = (uint8_t)(last >> 8);
}

size_t opxy_installer_write(struct opxy_master *m, unsigned form, bool image_ok, uint8_t *out)
{
	struct gate g = { &m->hw.flash, 0u, 0u, false, false, false, 0u, false, false };
	const struct s02_flash_ops ops = { &g, gate_read, gate_erase, gate_program };
	struct s02_env env = m->flash;
	struct s02_selector sel = { 0xFFu, 0xFFu };
	uint8_t sr = 0xFFu;
	unsigned target = 2u, t = 2u;
	bool good = false;
	int rc, sel_rc;

	env.flash = &ops;
	(void)wb_spiflash_status(&m->hw.flash, &sr);
	/* S-02.102 item 6: a settling that wrote nothing holds every write
	 * until a restart */
	rc = S02_OK;
	if (held_until_restart && form != OPXY_INSTALL_STATUS)
		rc = OPXY_INSTALL_REFUSED_HELD;
	/* S-02.102 item 4: the image's checks, all in memory, before the
	 * selector is read for the start condition */
	if (rc == S02_OK && env.crc32(0u, opxy_install_image, opxy_install_len) != opxy_install_crc)
		rc = S02_ERR_VERIFY;	/* the image as loaded, before the first erase */
	/* S-02.104: at most 0x76000 bytes, so slot k keeps its start log for
	 * the trial entry (S-02.095) and its settings sector */
	if (rc == S02_OK && (opxy_install_len == 0u || opxy_install_len > S02_STORE_SLOT_MAX))
		rc = S02_ERR_SIZE;
	if (rc == S02_OK && form != OPXY_INSTALL_STATUS && OPXY_TESTOS_SURVEY_ON)
		rc = OPXY_INSTALL_REFUSED_SURVEY;
	if (rc == S02_OK && form != OPXY_INSTALL_STATUS && !image_ok)
		rc = OPXY_INSTALL_REFUSED_IMAGE;	/* its stream, descriptor or front pin */
	/* S-02.091 in this run, for a commit as for a trial */
	if (rc == S02_OK && form != OPXY_INSTALL_STATUS &&
	    !s01_bootable(S01_BOOTLOADER, opxy_install_image, opxy_install_len))
		rc = S02_ERR_STREAM;
	if (rc == S02_OK)
		rc = s02_read_selector(&env, &sel);
	if (rc == S02_OK && form != OPXY_INSTALL_STATUS) {
		/* The selected slot is the way back: verified, and good now. */
		rc = s02_check_slot(&env, s02_selected_slot(sel.index), &good);
		if (rc == S02_OK && (!s02_verified(sel.verified) || !good))
			rc = S02_ERR_START;
	}
	if (rc == S02_OK && form != OPXY_INSTALL_STATUS) {
		t = s02_other_slot(sel.index);
		/* S-02.108: the OP-1F keeps a slot of the bootloader it came with */
		if (form == OPXY_INSTALL_TRIAL &&
		    !inst_keeps_factory(opxy_dev(m), t, streams_of(&env)))
			rc = OPXY_INSTALL_REFUSED_FACTORY;
	}
	if (rc == S02_OK && form != OPXY_INSTALL_STATUS) {
		g.slot = s02_slot_base(t);
		g.record = s02_record_off(t);
		g.armed = true;
	}
	if (rc == S02_OK && form == OPXY_INSTALL_TRIAL) {
		rc = trial_upgrade(&env, &g, &target);
		if (rc == S02_ERR_IO && g.at_selector && target == t)
			rc = trial_finish(&env, &g, t);
		if (held_until_restart)
			s14_log_str(&m->sv.log, S14_ERROR, S14_TAG("install"),
				    "selector step failed and left as it is: "
				    "no slot write until a restart");
	} else if (rc == S02_OK && form == OPXY_INSTALL_COMMIT) {
#if defined(OPXY_BOOT_CRUMBS_ON)
		/* BOOT_CRUMBS=1 defines OPXY_BOOT_CRUMBS_ON for the whole target
		 * build, this installer and the image it carries alike (the test
		 * OS leaves no marks): such an image runs only as a trial. */
		rc = OPXY_INSTALL_REFUSED_CRUMBS;
#else
		/* Only what a trial left: the record's wrong crc, the same bytes,
		 * the trial entry started, marked by slot k's own front in a start
		 * from slot k (S-02.095), as a select from recovery needs it
		 * (S-02.084), and the boot menu's mark that this build's main
		 * image adds in that start. */
		const uint8_t st = slot_state(&env, t);

		if ((st & OPXY_INSTALL_SLOT_TRIAL) == 0u)
			rc = S02_ERR_START;
		else if ((st & OPXY_INSTALL_SLOT_STARTED) == 0u)
			rc = OPXY_INSTALL_REFUSED_UNSTARTED;
		else if ((st & OPXY_INSTALL_SLOT_REACHED) == 0u)
			rc = OPXY_INSTALL_REFUSED_UNREACHED;
		else
			rc = commit_finish(&env, &g, t);
#endif
	}

	/* The reply: rc, status register, selector, each slot's state, the target,
	 * what the gate refused, the mirror. */
	out[0] = (uint8_t)rc;
	out[1] = sr;
	sel_rc = s02_read_selector(&env, &sel);
	out[2] = sel.index;
	out[3] = sel.verified;
	out[4] = slot_state(&env, 0u);
	out[5] = slot_state(&env, 1u);
	out[6] = (uint8_t)t;	/* the target; t is reused below */
	out[7] = (uint8_t)g.refused;
	out[8] = mirror_state(&env);
	/* A breadcrumb build's marks, from the unselected slot, and only when
	 * it holds this image: a factory bootloader's bytes do not leave here. */
	memset(out + 9, 0xFF, OPXY_INSTALL_CRUMBS);
	t = s02_other_slot(sel.index);
	if ((out[4u + t] & (OPXY_INSTALL_SLOT_TRIAL | OPXY_INSTALL_SLOT_COMMITTED)) != 0u)
		(void)gate_read(&g, last_sector(t), out + 9, OPXY_INSTALL_CRUMBS);
	/* The selected slot's start log, summed up, under the same rule. */
	memset(out + 9 + OPXY_INSTALL_CRUMBS, 0xFF, OPXY_INSTALL_LOG);
	out[9 + OPXY_INSTALL_CRUMBS] = 0u;
	t = s02_selected_slot(sel.index);
	if (sel_rc == S02_OK &&
	    (out[4u + t] & (OPXY_INSTALL_SLOT_TRIAL | OPXY_INSTALL_SLOT_COMMITTED)) != 0u)
		log_summary(&env, t, out + 9 + OPXY_INSTALL_CRUMBS);
	out[OPXY_INSTALL_STREAMS] = streams_of(&env);
	return OPXY_INSTALL_REPLY;
}

void opxy_installer_survey_read(struct opxy_master *m, struct inst_survey *sv)
{
	struct gate g = { &m->hw.flash, 0u, 0u, false, false, false, 0u, false, false };
	const struct s02_flash_ops ops = { &g, gate_read, gate_erase, gate_program };
	struct s02_env env = m->flash;
	struct s02_selector sel;
	unsigned k;

	/* reads alone: the gate is not armed, and a survey's refuses anyway */
	env.flash = &ops;
	sv->sel_read = s02_read_selector(&env, &sel) == S02_OK;
	sv->sel_index = sv->sel_read ? sel.index : 0xFFu;
	sv->sel_verified = sv->sel_read ? sel.verified : 0xFFu;
	for (k = 0; k < 2u; k++) {
		struct inst_slot_survey *sl = &sv->slot[k];
		uint8_t raw[S02_RECORD_SIZE];
		struct s02_record rec;
		bool good = false;

		memset(sl, 0, sizeof *sl);
		if (gate_read(&g, s02_record_off(k), raw, sizeof raw) == 0) {
			s02_record_decode(raw, &rec);
			sl->bits |= INST_SV_RECORD;
			sl->crc = rec.crc32;
			sl->length = rec.length;
			sl->tag = rec.tag;
		}
		if (s02_check_slot(&env, k, &good) == S02_OK && good)
			sl->bits |= INST_SV_GOOD;
		if (s02_stream_is_waffle(gate_read, &g, s02_slot_base(k), S02_SLOT_CAPACITY, crc_of))
			sl->bits |= INST_SV_WAFFLE;
		if (gate_read(&g, last_sector(k), sl->log, INST_SURVEY_LOG) == 0)
			sl->bits |= INST_SV_LOG;
	}
}
