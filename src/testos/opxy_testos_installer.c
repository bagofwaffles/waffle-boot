/* Generated by tools/installer_image.py: the image, and the front pin of
 * src/front/front.pin it must carry. */
extern const uint8_t opxy_install_image[];
extern const uint32_t opxy_install_len;
extern const uint32_t opxy_install_crc;
extern const uint8_t opxy_install_pin[32];

#define SCREEN_MS 100u		/* the hold's bar is drawn again this often */

static struct {
	struct inst_proto proto;
	struct inst_state st;
	struct inst_hello hello;
	struct inst_hold hold;
	struct inst_image img;
	bool image_ok;
	const struct tchk_table *table;
	const char *report;
	size_t report_len;
	uint8_t eng[OPXY_INSTALL_REPLY];
	bool eng_read;
	unsigned last_form;
	char version[24];
	const struct s06_port_ops *cdc;
} in;

/* --- the USB port: the protocol in place of the S-06 link --- */

static uint32_t crc_of(uint32_t crc, const uint8_t *p, size_t n)
{
	return wire_crc32(crc, p, (uint32_t)n);
}

static void flush(void)
{
	size_t n;
	const uint8_t *p = inst_proto_out(&in.proto, &n);

	if (n == 0u || !s10a_usb_cdc_open(NULL))
		return;
	{
		const size_t room = s10a_usb_cdc_room();
		const size_t k = n < room ? n : room;

		if (k != 0u)
			inst_proto_sent(&in.proto, s10a_usb_cdc_write(p, k));
	}
}

/* The link's read: every byte goes to the protocol, none to S-06. */
static size_t port_read(void *ctx, uint8_t *buf, size_t max)
{
	static const struct tchk_table empty;
	const struct inst_view v = {
		&in.hello, &in.st, in.table != NULL ? in.table : &empty, in.report, in.report_len,
	};
	uint8_t c;
	size_t n;

	(void)ctx;
	(void)buf;
	(void)max;
	flush();
	while (inst_proto_out(&in.proto, &n) != NULL && n == 0u && s10a_usb_cdc_read(&c, 1u) == 1u)
		(void)inst_proto_feed(&in.proto, &c, 1u, &v);
	flush();
	return 0;
}

static size_t port_room(void *ctx)
{
	(void)ctx;
	return 0;
}

static void port_write(void *ctx, const uint8_t *data, size_t n)
{
	(void)ctx;
	(void)data;
	(void)n;
}

static const struct s06_port_ops port = { port_read, port_room, port_write };

/* --- the carried image --- */

static void sha_init(void *ctx)
{
	br_sha256_init(ctx);
}

static void sha_update(void *ctx, const uint8_t *p, size_t n)
{
	br_sha256_update(ctx, p, n);
}

static void sha_final(void *ctx, uint8_t out[32])
{
	br_sha256_out(ctx, out);
}

static void version(void)
{
	struct tchk_text t;

	tchk_text_init(&t, sizeof in.version - 1u);
	tchk_put_dec(&t, in.hello.version[0]);
	tchk_put_str(&t, ".");
	tchk_put_dec(&t, in.hello.version[1]);
	tchk_put_str(&t, ".");
	tchk_put_dec(&t, in.hello.version[2]);
	memcpy(in.version, t.s, (size_t)t.n + 1u);
}

void opxy_installer_start(struct opxy_master *m)
{
	static br_sha256_context sha;
	const struct inst_sha_ops ops = { &sha, sha_init, sha_update, sha_final };

	inst_proto_init(&in.proto, crc_of);
	in.st.phase = INST_STARTING;
	in.st.verdict = 0xFFu;
	in.st.under_way = 0xFFu;
	in.st.target = 0xFFu;
	in.st.last_rc = 0xFFu;
	/* the carried image, before anything: its CRC, stream, descriptor and
	 * front pin */
	in.image_ok = inst_image_check(opxy_install_image, opxy_install_len, opxy_install_crc,
				       opxy_install_pin, crc_of, &ops, &in.img);
	memcpy(in.hello.version, in.img.version, sizeof in.hello.version);
	in.hello.len = opxy_install_len;
	in.hello.crc = opxy_install_crc;
	memcpy(in.hello.pin, in.img.desc_ok ? in.img.pin : opxy_install_pin, 32);
	in.st.flags = in.image_ok ? INST_F_IMAGE_OK : 0u;
#if defined(OPXY_BOOT_CRUMBS_ON)
	in.st.flags |= INST_F_CRUMBS;
#endif
	version();
	/* the serial port's bytes to the protocol */
	in.cdc = m->link[S06_LINK_CDC].ops;
	m->link[S06_LINK_CDC].ops = &port;
}

void opxy_installer_note(enum inst_phase phase, unsigned under_way)
{
	in.st.phase = (uint8_t)phase;
	in.st.under_way = (uint8_t)(under_way < TCHK_COUNT ? under_way : 0xFFu);
}

void opxy_installer_table(const struct tchk_table *t, const char *report, size_t len)
{
	in.table = t;
	in.report = report;
	in.report_len = len;
	in.st.verdict = (uint8_t)tchk_verdict(t);
}

size_t opxy_installer_report(char *out, size_t len, size_t cap)
{
	return inst_report_append(out, len, cap, &in.hello, &in.st, &in.img,
				  in.eng_read ? in.eng : NULL);
}

/* --- the flash as the engine sees it --- */

static void engine(struct opxy_master *m, unsigned form)
{
	(void)opxy_installer_write(m, form, in.image_ok, in.eng);
	in.eng_read = true;
	in.st.sel_index = in.eng[2];
	in.st.sel_verified = in.eng[3];
	in.st.slot_state[0] = in.eng[4];
	in.st.slot_state[1] = in.eng[5];
	in.st.target = (uint8_t)s02_other_slot(in.eng[2]);
	in.st.trial = (uint8_t)inst_trial_of(in.eng[4u + in.st.target]);
	if (form != OPXY_INSTALL_STATUS)
		in.st.last_rc = in.eng[0];
}

static bool selected_ok(void)
{
	const unsigned s = s02_selected_slot(in.st.sel_index);

	return in.eng[0] == S02_OK && s02_verified(in.st.sel_verified) &&
	       (in.st.slot_state[s] & OPXY_INSTALL_SLOT_GOOD) != 0u;
}

/* The phase the flash and the checks give, on entry. */
static enum inst_phase settle(const struct opxy_installer_ctx *c)
{
	const unsigned sel = s02_selected_slot(in.st.sel_index);

	in.st.lock = (uint8_t)inst_lock_of(c->t, c->sw, in.image_ok, selected_ok());
	if (in.st.lock != INST_LOCK_NONE)
		return INST_LOCKED;
	in.st.flags |= INST_F_UNLOCKED;
	if ((in.st.slot_state[sel] & OPXY_INSTALL_SLOT_COMMITTED) != 0u)
		return INST_DONE;	/* already the unit's bootloader */
	if (in.st.trial == INST_TRIAL_REACHED)
		return INST_COMMIT_READY;
	/* a start came after the trial was written, and this runs: the trial
	 * start did not reach the new boot menu */
	return in.st.trial == INST_TRIAL_NONE ? INST_READY : INST_TRIAL_FAILED;
}

/* The digits each phase lets a hold start. */
static uint16_t holds_for(enum inst_phase p, bool os_ok)
{
	const uint16_t back = os_ok ? 1u << 8 : 0u;

	if (p == INST_READY || p == INST_COMMIT_READY || p == INST_FAILED || p == INST_TRIAL_FAILED)
		return (uint16_t)(1u << 1 | back);
	if (p == INST_LOCKED || p == INST_DONE)
		return back;
	return 0;
}

static bool os_ok(const struct opxy_installer_ctx *c)
{
	return c->sw->result == TCHK_SW_READY;
}

static void draw(const struct opxy_installer_ctx *c, uint32_t now)
{
	struct inst_screen s;
	struct tchk_line l[S15_ROWS];
	unsigned n, i;

	memset(&s, 0, sizeof s);
	s.phase = in.st.phase;
	s.version = in.version;
	s.target = in.st.target;
	s.lock = in.st.lock;
	s.last_rc = in.st.last_rc;
	s.os = in.st.os;
	s.trial = in.st.trial;
	s.verdict = tchk_verdict(c->t);
	s.hold_digit = in.hold.holding ? in.hold.digit : 0u;
	s.hold_fill = inst_hold_fill(&in.hold, now);
	s.hold_left_s = in.hold.holding ?
		(S15_CONFIRM_HOLD_MS - (now - in.hold.t0 < S15_CONFIRM_HOLD_MS ?
					now - in.hold.t0 : S15_CONFIRM_HOLD_MS) + 999u) / 1000u : 0u;
	in.st.hold_fill = (uint16_t)s.hold_fill;
	in.st.hold_digit = (uint8_t)s.hold_digit;
	n = inst_screen_lines(&s, l);
	s15_console_clear(c->con);
	for (i = 0; i < n; i++)
		s15_console_add(c->con, (enum s15_style)l[i].style, l[i].s);
	c->show(c->m);
}

static void enter(const struct opxy_installer_ctx *c, enum inst_phase p, uint32_t now)
{
	in.st.phase = (uint8_t)p;
	in.st.os = (uint8_t)inst_os_state(c->sw);
	in.st.next_digit = (holds_for(p, os_ok(c)) & 1u << 1) != 0u ? 1u : 0u;
	inst_hold_offer(&in.hold, holds_for(p, os_ok(c)));
	c->report(c->m);
	draw(c, now);
}

/* The unit's OS made active again, through the suite's guard. */
static void leave(const struct opxy_installer_ctx *c)
{
	tchk_switch_write(c->env, c->sw);
	in.st.os = (uint8_t)inst_os_state(c->sw);
}

static uint32_t now_ms(const struct opxy_installer_ctx *c)
{
	return (uint32_t)wb_time_ms(&c->m->hw.time);
}

/* A write the hold started: its screen, the engine, what follows. */
static enum inst_phase write_form(const struct opxy_installer_ctx *c, unsigned form)
{
	in.last_form = form;
	enter(c, form == OPXY_INSTALL_COMMIT ? INST_COMMITTING : INST_WRITING_TRIAL, now_ms(c));
	c->pass(c->m);
	engine(c->m, form);
	if (in.st.last_rc != S02_OK)
		return INST_FAILED;
	if (form == OPXY_INSTALL_TRIAL)
		return INST_TRIAL_WRITTEN;
	/* kept: the unit's OS active again, part of the same step */
	leave(c);
	return INST_DONE;
}

static enum inst_phase act(const struct opxy_installer_ctx *c, unsigned digit)
{
	const enum inst_phase p = (enum inst_phase)in.st.phase;

	if (digit == 8u) {
		leave(c);
		return p == INST_DONE ? INST_DONE : INST_LEFT;
	}
	if (p == INST_READY || p == INST_TRIAL_FAILED)
		return write_form(c, OPXY_INSTALL_TRIAL);
	if (p == INST_COMMIT_READY)
		return write_form(c, OPXY_INSTALL_COMMIT);
	if (p == INST_FAILED)
		return write_form(c, in.last_form);
	return p;
}

bool opxy_installer_trial_back(struct opxy_master *m)
{
	if (!in.eng_read)
		engine(m, OPXY_INSTALL_STATUS);
	return in.st.trial != INST_TRIAL_NONE;
}

void opxy_installer_run(const struct opxy_installer_ctx *c)
{
	uint32_t drawn = 0;

	(void)opxy_installer_trial_back(c->m);
	in.st.flags |= INST_F_CHECKS_DONE;
	enter(c, settle(c), now_ms(c));
	for (;;) {
		const uint32_t now = now_ms(c);
		const bool was = in.hold.holding;
		unsigned key, digit;
		bool down;

		c->pass(c->m);
		while (c->next_key(&key, &down))
			inst_hold_key(&in.hold, key, s15_digit(key), down, now_ms(c));
		digit = inst_hold_tick(&in.hold, now_ms(c));
		if (digit != 0u) {
			enter(c, act(c, digit), now_ms(c));
			drawn = now_ms(c);
		} else if (was != in.hold.holding || (in.hold.holding && now - drawn >= SCREEN_MS)) {
			draw(c, now);
			drawn = now;
		}
	}
}

