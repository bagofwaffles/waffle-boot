"""The waffle-boot image the installer carries (wiki/Installer-Reference.md), as C.

    installer_image.py IMAGE.ldr PIN OUT.c

PIN is src/front/front.pin: the image's descriptor must carry that front pin, and the
installer checks the image against it again before it writes anything. Python 3, standard
library only.
"""
import struct
import sys
import zlib

CAPACITY = 0x77000      # S-02.044, less the slot's last sector: the start log (S-02.095)
DESC_MAGIC = 0x4D494257
DESC_ADDR = 0x08030000
DESC_O_PIN = 0x20


def descriptor_pin(data):
    """The front pin in the stream's descriptor block, or None (LDR blocks, S-05)."""
    off = 0
    while off + 16 <= len(data):
        code, target, count, _ = struct.unpack_from('<IIII', data, off)
        fill = code & 0x100
        payload = off + 16
        if target == DESC_ADDR and count >= DESC_O_PIN + 32 and not fill and \
                struct.unpack_from('<I', data, payload)[0] == DESC_MAGIC:
            return data[payload + DESC_O_PIN:payload + DESC_O_PIN + 32]
        off = payload + (0 if fill else count)
        if code & 0x8000:
            break
    return None


def main(argv):
    if len(argv) != 4:
        sys.exit(__doc__)
    with open(argv[1], 'rb') as f:
        data = f.read()
    with open(argv[2], encoding='ascii') as f:
        pin = bytes.fromhex(f.read().split()[0])
    if not 0 < len(data) <= CAPACITY:
        sys.exit('%s: %d bytes does not fit a slot before its start log' % (argv[1], len(data)))
    if len(pin) != 32:
        sys.exit('%s: not a front pin' % argv[2])
    got = descriptor_pin(data)
    if got != pin:
        sys.exit('%s: its descriptor does not carry the pinned front (%s)'
                 % (argv[1], 'none found' if got is None else got.hex()))
    with open(argv[3], 'w') as f:
        f.write('/* Generated by tools/installer_image.py. */\n#include <stdint.h>\n\n')
        f.write('const uint32_t opxy_install_len = %du;\n' % len(data))
        f.write('const uint32_t opxy_install_crc = 0x%08Xu;\n' % zlib.crc32(data))
        f.write('const uint8_t opxy_install_pin[32] = {%s};\n' % ','.join('%d' % b for b in pin))
        f.write('const uint8_t opxy_install_image[] = {\n')
        for i in range(0, len(data), 16):
            f.write(''.join('%d,' % b for b in data[i:i + 16]) + '\n')
        f.write('};\n')


if __name__ == '__main__':
    main(sys.argv)
