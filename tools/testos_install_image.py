"""The slot image the installer carries (docs/test-os.md, "The installer"), as C.

    testos_install_image.py IMAGE.ldr OUT.c

Python 3, standard library only.
"""
import sys
import zlib

CAPACITY = 0x77000      # S-02.044, less the slot's last sector: the start log (S-02.095)


def main(argv):
    if len(argv) != 3:
        sys.exit(__doc__)
    with open(argv[1], 'rb') as f:
        data = f.read()
    if not 0 < len(data) <= CAPACITY:
        sys.exit('%s: %d bytes does not fit a slot before its start log' % (argv[1], len(data)))
    with open(argv[2], 'w') as f:
        f.write('/* Generated by tools/testos_install_image.py. */\n#include <stdint.h>\n\n')
        f.write('const uint32_t opxy_install_len = %du;\n' % len(data))
        f.write('const uint32_t opxy_install_crc = 0x%08Xu;\n' % zlib.crc32(data))
        f.write('const uint8_t opxy_install_image[] = {\n')
        for i in range(0, len(data), 16):
            f.write(''.join('%d,' % b for b in data[i:i + 16]) + '\n')
        f.write('};\n')


if __name__ == '__main__':
    main(sys.argv)
