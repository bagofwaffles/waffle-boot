"""The registers S-13a expects at OS entry, as a C table for the test OS (docs/test-os.md).

    testos_regs.py OUT.c [--table register_states.tsv]

Reads tests/oracle/S-13a-core-bring-up/vectors/register_states.tsv and
writes the rows whose observation points include OSENTRY as `opxy_testos_regs[]` (waffle/testos.h),
with the field's bits, its rule (eq, ne, ge, le, in, any) and its bounds, so that the test OS can read
each register where the loading bootloader left it and log every field that differs. The table is
read, not applied. Python 3, standard library only.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TABLE = os.path.join(os.path.dirname(HERE), 'tests', 'oracle', 'S-13a-core-bring-up', 'vectors',
                     'register_states.tsv')
POINT = 'OSENTRY'
RULES = {'eq': 'OPXY_TESTOS_RULE_EQ', 'ne': 'OPXY_TESTOS_RULE_NE', 'ge': 'OPXY_TESTOS_RULE_GE',
         'le': 'OPXY_TESTOS_RULE_LE', 'in': 'OPXY_TESTOS_RULE_IN', 'any': 'OPXY_TESTOS_RULE_ANY'}


def num(s):
    return int(s, 0)


def rows(path=TABLE):
    """[(register, address, field, msb, lsb, rule, lo, hi, req)] of the OSENTRY rows."""
    out = []
    with open(path) as f:
        head = f.readline().rstrip('\n').split('\t')
        for line in f:
            if not line.strip():
                continue
            r = dict(zip(head, line.rstrip('\n').split('\t')))
            if POINT not in r['points'].split(','):
                continue
            bits = r['bits'].split(':')
            msb, lsb = (int(bits[0]), int(bits[-1]))
            rule = r['rule']
            if rule not in RULES:
                raise SystemExit('%s: unknown rule %r' % (path, rule))
            lo = hi = 0
            if rule == 'in':
                a, b = r['value'].split('..')
                lo, hi = num(a), num(b)
            elif rule != 'any':
                lo = num(r['value'])
            out.append((r['register'], num(r['address']), r['field'], msb, lsb, rule, lo, hi, r['req']))
    return out


def c_source(table):
    lines = ['/* SPDX-License-Identifier: GPL-2.0-or-later */',
             '/* Generated by tools/testos_regs.py from',
             ' * tests/oracle/S-13a-core-bring-up/vectors/register_states.tsv, point OSENTRY. */',
             '#include "waffle/testos.h"',
             '',
             'const struct opxy_testos_reg opxy_testos_regs[] = {']
    for reg, addr, field, msb, lsb, rule, lo, hi, req in table:
        lines.append('\t{ 0x%08Xu, %du, %du, %s, 0x%Xu, 0x%Xu, "%s", "%s", "%s" },'
                     % (addr, msb, lsb, RULES[rule], lo, hi, reg, field, req))
    lines += ['};', '', 'const unsigned opxy_testos_regs_n = %d;' % len(table), '']
    return '\n'.join(lines)


def main(argv):
    args = argv[1:]
    table = TABLE
    if '--table' in args:
        i = args.index('--table')
        table = args[i + 1]
        del args[i:i + 2]
    if len(args) != 1:
        print(__doc__)
        return 2
    src = c_source(rows(table))
    with open(args[0], 'w') as f:
        f.write(src)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
