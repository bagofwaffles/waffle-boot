"""Generate s02_vectors.h from tests/oracle/S-02-spi-flash/vectors.

Run from the repository root:  python3 -I -B tests/vectors/s02/gen_s02_vectors.py --out DIR
"""
import csv
import json
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import genout  # noqa: E402  (before anything the generator reads)

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
VEC = os.path.join(ROOT, 'tests', 'oracle', 'S-02-spi-flash', 'vectors')
OUT = 's02_vectors.h'

STATES = ['good', 'badcrc', 'badtag', 'erased', 'badlen', 'hugelen', 'empty']


def load_csv(name):
    with open(os.path.join(VEC, name), newline='') as f:
        return list(csv.DictReader(f))


def load_json(name):
    with open(os.path.join(VEC, name)) as f:
        return json.load(f)


def hexbytes(s):
    return [int(x, 16) for x in s.split()]


def carr(vals):
    return '{' + ', '.join('0x%02x' % v for v in vals) + '}'


def sel(s):
    b = hexbytes(s)
    return '{0x%02x, 0x%02x}' % (b[0], b[1])


def checks(s):
    """'slot0+slot1' -> order code: first slot, then 1 if a second was checked."""
    parts = s.split('+')
    first = int(parts[0][-1])
    second = int(parts[1][-1]) if len(parts) > 1 else 2
    return first, second


def main():
    out = []
    w = out.append
    w('/* SPDX-License-Identifier: GPL-2.0-or-later */')
    w('/* Generated by tests/vectors/s02/gen_s02_vectors.py from tests/oracle/S-02-spi-flash/vectors. */')
    w('/* Do not edit. */')
    w('#ifndef S02_VECTORS_H')
    w('#define S02_VECTORS_H')
    w('#include <stdint.h>')
    w('#include "waffle/s01_memmap.h"')
    w('')

    rec = load_json('records.json')
    w('/* records.json: selector */')
    w('struct v_selector { uint8_t index, verified; unsigned slot; int check_next; };')
    w('static const struct v_selector v_selectors[] = {')
    for r in rec['selector']:
        b = hexbytes(r['bytes'])
        w('\t{0x%02x, 0x%02x, %d, %d},' % (b[0], b[1], r['selected_slot'], int(r['check_on_next_boot'])))
    w('};')
    w('struct v_record { const char *name; uint8_t bytes[12]; uint32_t crc32, length, tag; int tag_ok, len_ok; };')
    w('static const struct v_record v_records[] = {')
    for r in rec['record']:
        w('\t{"%s", %s, %s, %s, %s, %d, %d},' % (
            r['name'], carr(hexbytes(r['bytes'])), r['crc32'], r['length'], r['tag'],
            int(r['tag_ok']), int(r['length_in_range'])))
    w('};')
    w('/* kind 0: the bytes of data; 1: len bytes of fill; 2: ((i*7+seed) ^ (i>>8)) & 0xff */')
    w('struct v_crc { int kind; const char *data; uint32_t len; uint8_t fill; uint32_t seed; uint32_t crc32; };')
    w('static const struct v_crc v_crcs[] = {')
    for r in rec['crc']:
        if 'data_ascii' in r:
            d = r['data_ascii'].encode()
            w('\t{0, %s, %d, 0, 0, %s},' % (json.dumps(r['data_ascii']), len(d), r['crc32']))
        elif 'data_hex' in r:
            d = bytes(hexbytes(r['data_hex']))
            w('\t{0, "%s", %d, 0, 0, %s},' % (''.join('\\x%02x' % c for c in d), len(d), r['crc32']))
        elif 'fill' in r:
            w('\t{1, "", %d, %s, 0, %s},' % (r['length'], r['fill'], r['crc32']))
        elif 'pattern' in r:
            assert r['pattern'] == '((i*7+seed) ^ (i>>8)) & 0xff'
            w('\t{2, "", %d, 0, %d, %s},' % (r['length'], r['seed'], r['crc32']))
        else:
            w('\t{0, "", %d, 0, 0, %s},' % (r['length'], r['crc32']))
    w('};')
    w('')

    # first_stage_table.csv
    w('/* first_stage_table.csv.  states index STATES; checks: first slot, second (2 = none). */')
    w('static const char *const v_states[] = {%s};' % ', '.join('"%s"' % s for s in STATES))
    w('struct v_fs { uint8_t sel[2]; uint8_t s0, s1;')
    w('\tuint8_t c_first, c_second, c_pass, c_boot, c_after[2], c_writes, c_boot2, c_after2[2];')
    w('\tint8_t f_boot; uint8_t f_after[2]; int8_t f_writes, f_boot2; uint8_t f_after2[2]; };')
    w('static const struct v_fs v_first_stage[] = {')
    for r in load_csv('first_stage_table.csv'):
        a, b = checks(r['conforming_checks'])
        fu = r['factory_boot'] == 'unspecified'

        def fsel(s):
            return '{0, 0}' if s == 'unspecified' else sel(s)
        w('\t{%s, %d, %d, %d, %d, %d, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s},' % (
            sel(r['selector']), STATES.index(r['slot0']), STATES.index(r['slot1']),
            a, b, int(r['conforming_result'] == 'pass'), r['conforming_boot'],
            sel(r['conforming_sel_after']), r['conforming_writes'], r['conforming_reset2_boot'],
            sel(r['conforming_reset2_sel_after']),
            '-1' if fu else r['factory_boot'], fsel(r['factory_sel_after']),
            '-1' if r['factory_writes'] == 'unspecified' else r['factory_writes'],
            '-1' if r['factory_reset2_boot'] == 'unspecified' else r['factory_reset2_boot'],
            fsel(r['factory_reset2_sel_after'])))
    w('};')
    w('')

    # first_stage_read_faults.csv
    w('/* first_stage_read_faults.csv.  faults: 1 selector, 2 slot 0, 4 slot 1; checks as above. */')
    w('struct v_fsf { uint8_t sel[2]; uint8_t s0, s1, faults, seen, c_first, c_second, boot;')
    w('\tuint8_t after[2], writes; };')
    w('static const struct v_fsf v_fs_faults[] = {')
    bits = {'selector': 1, 'slot0': 2, 'slot1': 4}
    for r in load_csv('first_stage_read_faults.csv'):
        a, b = checks(r['checks'])
        mask = sum(bits[x] for x in r['faults'].split('+'))
        w('\t{%s, %d, %d, %d, %s, %d, %d, %s, %s, %s},' % (
            sel(r['selector']), STATES.index(r['slot0']), STATES.index(r['slot1']), mask,
            r['fault_seen'], a, b, r['boot'], sel(r['sel_after']), r['writes']))
    w('};')
    w('')

    # metadata_writes.json
    m = load_json('metadata_writes.json')
    w('/* metadata_writes.json */')
    for name in ('old_record', 'new_record', 'other_writer_record', 'mirror_of_old'):
        b = hexbytes(m[name])
        w('static const uint8_t v_meta_%s[%d] = %s;' % (name, len(b), carr(b)))
    for i, t in enumerate(m['tail']):
        b = hexbytes(t['bytes'])
        w('static const uint8_t v_meta_tail%d[%d] = %s;' % (i, len(b), carr(b)))
        w('static const uint32_t v_meta_tail%d_off = %s;' % (i, t['offset']))
    w('struct v_op { char kind; uint32_t off, len; };')

    def ops(seq, name):
        w('static const struct v_op %s[] = {' % name)
        for o in seq:
            w("\t{'%s', %s, %d}," % (o['op'][0], o['offset'], o['length']))
        w('};')
    ops(m['write_sequences']['conforming'], 'v_meta_write_ops')
    ops(m['restore_sequences']['pending_old'], 'v_meta_restore_old_ops')
    ops(m['restore_sequences']['pending_erased'], 'v_meta_restore_erased_ops')
    w('')

    # metadata_cuts.csv, conforming rule, the cuts the C fake can reproduce.
    w('/* metadata_cuts.csv rule conforming: start 0 mirror_old, 1 mirror_absent, 2 pending_old,')
    w(' * 3 pending_erased; op_n counts every op of the vector sequence (reads too);')
    w(' * tear: 0 none (after), 1 zeros, 2 ones, 3 bit (a, b); result 0 old, 1 new. */')
    w('struct v_mcut { int start; int restore; unsigned op_n; int tear; uint32_t a, b;')
    w('\tint mirror_valid; int restored; int result; int factory_kept; int tail_kept; };')
    w('static const struct v_mcut v_meta_cuts[] = {')
    starts = ['mirror_old', 'mirror_absent', 'pending_old', 'pending_erased']
    for r in load_csv('metadata_cuts.csv'):
        if r['rule'] != 'conforming' or r['start'] not in starts:
            continue
        tear, a, b = 0, 0, 0
        if r['kind'] == 'torn':
            p = r['pattern']
            if p.startswith('seed:'):
                continue
            kind, arg = p.split(':')
            if kind == 'bit':
                tear = 3
                a, b = (int(x) for x in arg.split('.'))
            else:
                tear = 1 if kind == 'zeros' else 2
                a, b = (int(x) for x in arg.split('-'))
        assert r['safe'] == 'yes' and r['fields_ok'] == 'yes'
        w('\t{%d, %d, %s, %d, %d, %d, %d, %d, %d, %d, %d},' % (
            starts.index(r['start']), int(r['phase'] == 'restore'), r['op_n'], tear, a, b,
            int(r['mirror_valid'] == 'yes'), int(r['restored'] == 'yes'),
            int(r['result'] == 'new'), int(r['factory_kept'] == 'yes'), int(r['tail_kept'] == 'yes')))
    w('};')
    w('')

    # powercut_sequences.json, conforming writer.
    pc = load_json('powercut_sequences.json')
    w('/* powercut_sequences.json, writer_rule conforming.  ops: erases and programs only. */')
    w('#define V_PC_IMAGE_LEN %du' % pc['image_length'])
    w('struct v_pcop { char kind; uint32_t off, len; uint8_t cls; };')
    classes = ['slot_erase', 'slot_program', 'record_erase', 'record_program', 'readback',
               'selector_erase', 'selector_program', 'selector_readback']
    seqs = [s for s in pc['sequences'] if s['writer_rule'] == 'conforming']
    for s in seqs:
        w('static const struct v_pcop v_pc_ops_%s[] = {' % s['id'].replace('-', '_'))
        for o in s['ops']:
            w("\t{'%s', %s, %d, %d}," % (o['op'][0], o['offset'], o['length'], classes.index(o['class'])))
        w('};')
    w('struct v_pcseq { const char *id; uint8_t sel[2]; uint8_t s0, s1; int precondition;')
    w('\tunsigned selected, target; uint8_t written[2]; int start_allowed;')
    w('\tint safe_f, safe_c, multi_f, multi_c; const struct v_pcop *ops; unsigned nops; };')
    w('static const struct v_pcseq v_pc_seqs[] = {')
    for s in seqs:
        sid = s['id'].replace('-', '_')
        sm = s.get('safe_multicut') or {}
        w('\t{"%s", %s, %d, %d, %d, %d, %d, %s, %d, %d, %d, %d, %d, v_pc_ops_%s, %d},' % (
            s['id'], sel(s['start']['selector']), STATES.index(s['start']['slot0']),
            STATES.index(s['start']['slot1']), int(s['precondition']), s['selected'], s['target'],
            sel(s['selector_written']), int(s['start_allowed']),
            int(s['safe']['factory']), int(s['safe']['conforming']),
            int(bool(sm.get('factory'))), int(bool(sm.get('conforming'))),
            sid, len(s['ops'])))
    w('};')
    w('')

    # powercut_cuts.csv joined with upgrade_cut_boots.csv, conforming sequences.
    after_cut = {(r['sequence'], r['op_n'], r['kind']): r for r in load_csv('upgrade_cut_boots.csv')}
    w('/* powercut_cuts.csv (conforming sequences): mut = erases and programs completed before')
    w(' * the cut (after) or the 1-based number of the torn one; boots: 3 resets per profile;')
    w(' * target_good / phase from upgrade_cut_boots.csv where it has the row (-1 if not). */')
    w('struct v_pccut { const char *id; unsigned op_n; int torn; unsigned mut; uint8_t sel_after[2];')
    w('\tuint8_t s0_good, s1_good; uint8_t boots_f[3], boots_c[3]; int safe_f, safe_c, multi_f, multi_c;')
    w('\tint target_good; };')
    w('static const struct v_pccut v_pc_cuts[] = {')
    byid = {s['id']: s for s in seqs}
    for r in load_csv('powercut_cuts.csv'):
        s = byid.get(r['sequence'])
        if s is None or r['kind'] == 'none':
            continue
        n = int(r['op_n'])
        prior = [o for o in s['ops'] if o['n'] <= n and o['op'] != 'read']
        torn = r['kind'] == 'torn'
        mut = len(prior)
        if torn and s['ops'][n - 1]['op'] == 'read':
            torn = False	# a cut inside a read changes nothing: the boundary before it
        rr = after_cut.get((r['sequence'], r['op_n'], r['kind']))
        tg = -1
        if rr is not None:
            tg = int(rr['target_state'] == 'good')
        def boots(v):	# 9: the vector lets it vary (a torn selector)
            return [9, 9, 9] if v.startswith('varies') else [int(x) for x in v.split()]
        bf = boots(r['factory_boots'])
        bc = boots(r['conforming_boots'])
        w('\t{"%s", %d, %d, %d, %s, %d, %d, {%d, %d, %d}, {%d, %d, %d}, %d, %d, %d, %d, %d},' % (
            r['sequence'], n, int(torn), mut, sel(r['selector'].replace('superset_of ', '')),
            int(r['slot0'] == 'good'), int(r['slot1'] == 'good'), *bf, *bc,
            int(r['factory_safe'] == 'True'), int(r['conforming_safe'] == 'True'),
            int(r['factory_safe_multicut'] == 'True'), int(r['conforming_safe_multicut'] == 'True'),
            tg))
    w('};')
    w('')

    # bootable_images.json (S-02.091): refused is the S01_SRULE_ bit of refused_by.
    bi = load_json('bootable_images.json')
    rules = {'parse': 'PARSE', 'inside_spaces': 'INSIDE_SPACES',
             'record_and_rom_stack': 'RECORD_AND_ROM_STACK', 'on_chip_only': 'ON_CHIP_ONLY',
             'one_init_block': 'ONE_INIT_BLOCK', 'init_in_l1': 'INIT_IN_L1',
             'init_before_ddr': 'INIT_BEFORE_DDR', 'spares_first_stage_stack': 'SPARES_FS_STACK',
             'rom_boot_reserve': 'ROM_BOOT_RESERVE', 'bcode': 'BCODE'}
    w('/* bootable_images.json.  slot: the image is a slot image (every case);')
    w(' * refused: the S01_SRULE_ bit of refused_by (0 when accepted). */')
    # S-02.091 rule 4: the factory first stage's stack and the boot-entry call's (S-01.022).
    w('#define V_FACTORY_FS_STACK_START %su' % bi['boot_call_stack'][0])
    w('#define V_FACTORY_FS_STACK_END %su' % bi['boot_call_stack'][1])
    for c in bi['cases']:
        b = bytes.fromhex(c['image'])
        assert len(b) == c['length'], c['name']
        w('static const uint8_t v_boot_%s[%d] = %s;' % (c['name'], len(b), carr(b)))
    w('struct v_bootable { const char *name; int slot; int accepted; uint32_t refused;')
    w('	const uint8_t *image; uint32_t length; };')
    w('static const struct v_bootable v_bootables[] = {')
    for c in bi['cases']:
        rb = c.get('refused_by')
        w('	{"%s", %d, %d, %s, v_boot_%s, %d},' % (
            c['name'], int(c['kind'] == 'slot'), int(c['accepted']),
            'S01_SRULE_' + rules[rb] if rb else '0u', c['name'], c['length']))
    w('};')
    w('')
    # slot_kinds.json (S-02.106): each case's bytes are its fill with its patches.
    sk = load_json('slot_kinds.json')
    w('/* slot_kinds.json: byte i of a case is (i * 37 + seed) & 0xff, then its patches;')
    w(' * kind 0 WB, 1 TE with a version, 2 TE alone, 3 ??. */')
    w('struct v_skind_patch { uint32_t off; uint8_t b[4]; };')
    w('struct v_skind { const char *name; uint32_t length; uint8_t seed; unsigned npatch;')
    w('\tstruct v_skind_patch patch[2]; uint32_t crc32; int desc_valid; uint16_t desc_version[4];')
    w('\tint kind; uint16_t version[4]; };')
    w('static const struct v_skind v_slot_kinds[] = {')
    for c in sk['cases']:
        assert len(c['patches']) <= 2 and 0 <= c['seed'] <= 255, c['name']
        pats = [(int(p['offset']), bytes.fromhex(p['bytes'])) for p in c['patches']]
        pats += [(0, bytes(4))] * (2 - len(pats))
        if c['kind'] == 'WB':
            kind = 0
        elif c['kind'] == 'TE':
            kind = 1 if c['version'] else 2
        else:
            assert c['kind'] == '??', c['name']
            kind = 3
        dv = c['descriptor_version'] or [0, 0, 0, 0]
        v = c['version'] if kind == 1 else [0, 0, 0, 0]
        w('\t{"%s", %d, %d, %d, {%s}, %s, %d, {%s}, %d, {%s}},' % (
            c['name'], c['length'], c['seed'], len(c['patches']),
            ', '.join('{%d, %s}' % (o, carr(list(bb))) for o, bb in pats), c['crc32'],
            int(c['descriptor_valid']), ', '.join(str(x) for x in dv), kind,
            ', '.join(str(x) for x in v)))
    w('};')
    w('')
    w('#endif /* S02_VECTORS_H */')

    text = '\n'.join(out) + '\n'
    genout.write(OUT, text)
    genout.finish()
    return 0


if __name__ == '__main__':
    sys.exit(main())
