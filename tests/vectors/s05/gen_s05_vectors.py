"""Generate s05_vectors.h from tests/oracle/S-05-os-handoff and tests/oracle/S-01-boot-chain.

Run from the repository root:  python3 -I -B tests/vectors/s05/gen_s05_vectors.py --out DIR
The C test reads the .ldr streams from tests/oracle/S-05-os-handoff/vectors at run time. The memory each
synthetic OS leaves is given here as a CRC-32 per region, computed by kernel_model.py and checked against
the vector's SHA-256 first.
"""
import binascii
import csv
import hashlib
import json
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import genout  # noqa: E402  (before anything the generator reads)

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
S05 = os.path.join(ROOT, 'tests', 'oracle', 'S-05-os-handoff')
S01 = os.path.join(ROOT, 'tests', 'oracle', 'S-01-boot-chain')
OUT = 's05_vectors.h'
sys.path.insert(0, S05)
import kernel_model  # noqa: E402
sys.path.insert(0, S01)
import check_layout  # noqa: E402


def js(path):
    with open(path) as f:
        return json.load(f)


def main():
    out = []
    w = out.append
    w('/* SPDX-License-Identifier: GPL-2.0-or-later */')
    w('/* Generated by tests/vectors/s05/gen_s05_vectors.py from tests/oracle/S-05-os-handoff and')
    w(' * tests/oracle/S-01-boot-chain. Do not edit. */')
    w('#ifndef S05_VECTORS_H')
    w('#define S05_VECTORS_H')
    w('#include <stdint.h>')
    w('')

    with open(os.path.join(S05, 'boot_decision.tsv'), newline='') as f:
        rows = list(csv.DictReader([l for l in f if not l.startswith('#')], delimiter='\t'))
    w('/* boot_decision.tsv: reason -1 = no record (reason 20 taken); keys 0 not_held 1 held 2 silent;')
    w(' * cleared: the boot sets the state word to 0 (S-11.080) */')
    w('struct v_dec { int reason; uint32_t state; int keys; int boot; int cleared; };')
    w('static const struct v_dec v_decisions[] = {')
    for r in rows:
        cleared = 'written' in r['state_after']
        assert r['state_after'].startswith('0x0000' if cleared else r['state'])
        assert cleared or 'unchanged' in r['state_after']
        w('\t{%s, %s, %d, %d, %d},' % (
            '-1' if r['reason'] == 'none' else r['reason'], r['state'],
            ['not_held', 'held', 'silent'].index(r['keys']), int(r['decision'] == 'boot'),
            int(cleared)))
    w('};')
    w('')

    cc = js(os.path.join(S05, 'vectors', 'compatibility_cases.json'))
    reasons = ['', 'length', 'parse', 'flags', 'space', 'staging', 'reserve', 'record', 'boot reserve']
    w('/* compatibility_cases.json: reason indexes v_refusals (0 accepted) */')
    w('struct v_compat { const char *image; int reason; };')
    w('static const struct v_compat v_compat[] = {')
    for c in cc['cases']:
        w('\t{"%s", %d},' % (c['image'], reasons.index(c.get('reason', '')) if c['refuse'] else 0))
    w('};')
    w('')

    w('/* synthetic_os_a/b.json; memory regions as CRC-32 of the kernel model\'s bytes */')
    w('struct v_call { uint32_t psource, dest, count; };')
    w('struct v_mem { uint32_t start, length, crc32; };')
    for name in ('synthetic_os_a', 'synthetic_os_b'):
        v = js(os.path.join(S05, 'vectors', name + '.json'))
        with open(os.path.join(S05, 'vectors', v['image']), 'rb') as f:
            img = f.read()
        assert hashlib.sha256(img).hexdigest() == v['sha256'] and len(img) == v['length']
        hb = int(v['header_buffer'], 16)
        model = kernel_model.load(img, hb)
        calls = [tuple(int(x, 16) for x in c) for c in v['calls']]
        assert calls == [tuple(c) for c in model['calls']]
        assert model['svect0'] == int(v['entry'], 16)
        assert model['final_psource'] == int(v['final_psource'], 16)
        w('static const struct v_call v_calls_%s[] = {' % name[-1])
        for c in calls:
            w('\t{0x%x, 0x%x, 0x%x},' % c)
        w('};')
        w('static const struct v_mem v_mem_%s[] = {' % name[-1])
        for m in v['memory']:
            start, length = int(m['start'], 16), int(m['length'], 16)
            data = model['memory'][start]
            assert len(data) == length and hashlib.sha256(data).hexdigest() == m['sha256']
            w('\t{0x%x, 0x%x, 0x%08x},' % (start, length, binascii.crc32(data)))
        w('};')
        w('#define V_%s_LEN %du' % (name[-1].upper(), len(img)))
        w('#define V_%s_ENTRY %su' % (name[-1].upper(), v['entry']))
        w('#define V_%s_HB %su' % (name[-1].upper(), v['header_buffer']))
        w('#define V_%s_FINAL %su' % (name[-1].upper(), v['final_psource']))
    w('')

    bc = js(os.path.join(S05, 'vectors', 'boot_config.json'))
    w('/* boot_config.json */')
    w('#define V_KERNEL %su' % bc['boot_kernel_entry'])
    w('#define V_CONFIG_SIZE %su' % bc['config_size'])
    w('#define V_PHEADER %su' % bc['config_nonzero_fields']['pHeader'])
    w('#define V_PLOADFN %su' % bc['config_nonzero_fields']['bootRegistry.pLoadFunction'])
    w('#define V_PSOURCE %su' % bc['load_function_reads']['pSource'])
    w('#define V_PDEST %su' % bc['load_function_reads']['pDestination'])
    w('#define V_COUNT %su' % bc['load_function_reads']['dByteCount'])
    w('')

    mm = js(os.path.join(S01, 'memory_map.json'))
    w('/* S-01 memory_map.json */')
    w('struct v_space { const char *name; uint32_t start; uint64_t end; };')
    w('static const struct v_space v_spaces[] = {')
    for s in mm['spaces']:
        w('\t{"%s", %s, %su},' % (s['name'], s['start'], s['end']))
    w('};')
    for k in ('rom_boot_reserve', 'record_and_rom_stack', 'reboot_record', 'staging', 'fatal_record',
              'display_record'):
        w('#define V_%s_START %su' % (k.upper(), mm[k]['start']))
        w('#define V_%s_END %su' % (k.upper(), mm[k]['end']))
    for i, r in enumerate(mm['handover_reserve']):
        w('#define V_RESERVE%d_START %su' % (i, r['start']))
        w('#define V_RESERVE%d_END %su' % (i, r['end']))
    for k in ('boot_kernel', 'boot', 'otp_get', 'otp_cfg', 'first_stage_boot_command', 'rom_reset_sp',
              'rom_l2_entry_sp_min', 'rom_l1_entry_sp', 'entry_stack_budget'):
        w('#define V_ROM_%s %su' % (k.upper(), mm['rom'][k]))
    w('#define V_ROM_RESET_STACK_START %su' % mm['rom']['rom_reset_stack']['start'])
    w('#define V_ROM_RESET_STACK_END %su' % mm['rom']['rom_reset_stack']['end'])
    w('#define V_RCU0_SVECT0 %su' % mm['mmr']['RCU0_SVECT0'])
    w('#define V_RECORD_FLOOR %su' % mm['record_floor'])
    w('')

    kinds = ['code', 'data', 'stack', 'heap', 'held_buffer']
    rules = ['handover_in_reserve', 'handover_not_staging', 'handover_no_heap', 'staging_clear',
             'held_buffers_clear', 'record_clear', 'display_record_clear', 'inside_spaces', 'heap_clear']
    w('/* S-01 vectors/layout_*.json: fail: the rules the vector requires to fail (s01 rule bits); exact: what check_layout.py reports */')
    w('struct v_region { uint32_t start; uint64_t end; int kind; int handover; };')
    # held_room (S-01.016's room for the RAM disk) is a property of the held-mode buffers, not one of
    # s01_layout_check's rules: a vector that requires it to fail is left out, and it is not counted.
    names = sorted(n for n in os.listdir(os.path.join(S01, 'vectors')) if n.startswith('layout_')
                   and set(js(os.path.join(S01, 'vectors', n))['expect'].get('fail', [])) <= set(rules))
    for i, n in enumerate(names):
        v = js(os.path.join(S01, 'vectors', n))
        w('static const struct v_region v_layout_%d[] = {' % i)
        for r in v['ranges']:
            w('\t{%s, %su, %d, %d},' % (r['start'], r['end'], kinds.index(r['kind']), int(r.get('handover', False))))
        w('};')
    w('struct v_layout { const char *name; const struct v_region *r; unsigned n; uint32_t fail; uint32_t exact; int all; };')
    w('static const struct v_layout v_layouts[] = {')
    for i, n in enumerate(names):
        v = js(os.path.join(S01, 'vectors', n))
        mask = 0
        for f in v['expect'].get('fail', []):
            mask |= 1 << rules.index(f)
        exact = 0
        for rule, ok, _ in check_layout.check(v):
            if not ok and rule in rules:
                exact |= 1 << rules.index(rule)
        assert exact & mask == mask
        w('\t{"%s", v_layout_%d, %d, 0x%x, 0x%x, %d},' % (n, i, len(v['ranges']), mask, exact,
                                                         int(v['expect'].get('all', False))))
    w('};')
    w('')

    d = js(os.path.join(S05, 'vectors', 'os_destinations_1f.json'))
    st = bytes.fromhex(d['stream'])
    w('/* os_destinations_1f.json (S-05.040): the stream in OS 1.7.3\'s shape and its ranges */')
    w('static const uint8_t v_os1f_stream[] = {%s};' % ', '.join('0x%02x' % b for b in st))
    w('#define V_OS1F_ACCEPTED %d' % int(d['verdict']['accepted']))
    w('struct v_os1f_range { uint32_t start, end; int fill; };')
    w('static const struct v_os1f_range v_os1f_ranges[] = {')
    for r in d['ranges']:
        w('\t{%su, %su, %d},' % (r['start'], r['end'], int(r['fill'])))
    w('};')
    e = js(os.path.join(S05, 'vectors', 'entry_state_1f.json'))
    w('/* entry_state_1f.json (S-05.038): EVT0 to EVT15, 0 for none given */')
    w('static const uint32_t v_entry1f_evt[16] = {%s};' % ', '.join(
        e['evt'].get('EVT%d' % i, '0') + 'u' for i in range(16)))
    w('')
    w('#endif /* S05_VECTORS_H */')
    genout.write(OUT, '\n'.join(out) + '\n')
    genout.finish()
    return 0


if __name__ == '__main__':
    sys.exit(main())
