"""Generate s04_vectors.h from tests/oracle/S-04-records.

Run from the repository root:  python3 -I -B tests/vectors/s04/gen_s04_vectors.py --out DIR
"""
import csv
import json
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import genout  # noqa: E402  (before anything the generator reads)

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
SPEC = os.path.join(ROOT, 'tests', 'oracle', 'S-04-records')
OUT = 's04_vectors.h'


def tsv(name):
    with open(os.path.join(SPEC, name), newline='') as f:
        rows = [line for line in f if not line.startswith('#')]
    return list(csv.DictReader(rows, delimiter='\t'))


def js(name):
    with open(os.path.join(SPEC, 'vectors', name)) as f:
        return json.load(f)


def hx(s):
    return bytes.fromhex(s.replace(' ', ''))


def carr(b):
    return '{' + ', '.join('0x%02x' % c for c in b) + '}'


def cstr(s):
    return 'NULL' if s is None else json.dumps(s)


def main():
    out = []
    w = out.append
    w('/* SPDX-License-Identifier: GPL-2.0-or-later */')
    w('/* Generated by tests/vectors/s04/gen_s04_vectors.py from tests/oracle/S-04-records. Do not edit. */')
    w('#ifndef S04_VECTORS_H')
    w('#define S04_VECTORS_H')
    w('#include <stddef.h>')
    w('#include <stdint.h>')
    w('')

    rr = js('reboot_record.json')
    w('/* reboot_record.json */')
    w('struct v_rr_encode { uint16_t reason; uint8_t bytes6[6]; };')
    w('static const struct v_rr_encode v_rr_encode[] = {')
    for r in rr['encode']:
        w('\t{%d, %s},' % (r['reason'], carr(hx(r['bytes6']))))
    w('};')
    w('struct v_rr_decode { uint8_t bytes[8]; int present; uint16_t reason; };')
    w('static const struct v_rr_decode v_rr_decode[] = {')
    for r in rr['decode']:
        w('\t{%s, %d, %d},' % (carr(hx(r['bytes'])), int(r['present']), r.get('reason', 0)))
    w('};')
    w('struct v_rr_write { uint8_t before[8]; uint16_t reason; uint8_t after[8]; };')
    w('static const struct v_rr_write v_rr_write[] = {')
    for r in rr['write']:
        w('\t{%s, %d, %s},' % (carr(hx(r['before'])), r['reason'], carr(hx(r['after']))))
    w('};')
    w('struct v_rr_consume { uint8_t before[8]; uint16_t taken; uint8_t after[8]; };')
    w('static const struct v_rr_consume v_rr_consume[] = {')
    for r in rr['consume']:
        w('\t{%s, %d, %s},' % (carr(hx(r['before'])), r['taken'], carr(hx(r['after']))))
    w('};')
    w('#define V_RR_ADDR %su' % rr['address']['start'])
    w('')

    w('/* reason_table.tsv: screen 0 main 1 upgrade; transport 0 none 1 msc 2 midi */')
    w('struct v_reason { uint8_t record[8]; uint16_t taken; int boots, screen, cdc, transport; uint8_t after[8]; };')
    w('static const struct v_reason v_reasons[] = {')
    for r in tsv('reason_table.tsv'):
        w('\t{%s, %s, %d, %d, %d, %d, %s},' % (
            carr(hx(r['record'])), r['reason_taken'], int(r['boots'] == 'yes'),
            ['main', 'upgrade'].index(r['screen']), int(r['cdc'] == 'yes'),
            ['-', 'msc', 'midi'].index(r['transport']), carr(hx(r['record_after']))))
    w('};')
    w('')

    w('/* host_modes.tsv */')
    w('struct v_hostmode { uint8_t payload[4]; size_t len; uint16_t reason; };')
    w('static const struct v_hostmode v_host_modes[] = {')
    for r in tsv('host_modes.tsv'):
        p = b'' if r['mode_payload'] == '-' else hx(r['mode_payload'])
        w('\t{%s, %d, %s},' % (carr(p + bytes(4 - len(p))), len(p), r['reason']))
    w('};')
    w('')

    w('/* writers.tsv: reason -1 host mode, -2 the reason taken; reset 0 hard 1 soft;')
    w(' * nordic 0 none 1 enter 2 exit; shutdown 0 no 1 yes 2 n/a */')
    w('struct v_writer { int id; int reason; int reset; int nordic; int shutdown; int psoc_reset; uint32_t delay; };')
    w('static const struct v_writer v_writers[] = {')
    for r in tsv('writers.tsv'):
        reason = {'host_modes.tsv': -1, 'taken': -2}.get(r['reason'])
        if reason is None:
            reason = int(r['reason'])
        w('\t{%s, %d, %d, %d, %d, %d, %s},' % (
            r['id'][1:], reason, ['hard', 'soft'].index(r['reset']),
            ['none', 'enter', 'exit'].index(r['nordic']), ['no', 'yes', 'n/a'].index(r['shutdown']),
            int(r['psoc_reset'] == 'yes'), r['min_delay_ms']))
    w('};')
    w('')

    m = js('metadata.json')
    w('/* metadata.json; state as a number; serial "" = empty. */')
    w('struct v_meta_fields { const char *serial; uint16_t sku, factory; uint16_t os[4], sw[4]; uint32_t state; int has; };')

    def fields(f):
        # has: bit 0 serial, 1 sku, 2 factory, 3 os, 4 sw, 5 state
        has = 0
        for i, k in enumerate(['serial', 'sku', 'factory', 'os_version', 'sw_version', 'state']):
            if k in f:
                has |= 1 << i
        os_v = f.get('os_version', [0, 0, 0, 0])
        sw_v = f.get('sw_version', [0, 0, 0, 0])
        return '{%s, %d, %d, {%s}, {%s}, %s, 0x%x}' % (
            json.dumps(f.get('serial', '')), f.get('sku', 0), f.get('factory', 0),
            ', '.join(map(str, os_v)), ', '.join(map(str, sw_v)), f.get('state', '0x0'), has)
    e = m['encode'][0]
    w('static const uint8_t v_meta_encode_bytes[] = %s;' % carr(hx(e['bytes'])))
    w('static const struct v_meta_fields v_meta_encode_fields = %s;' % fields(e['fields']))
    w('#define V_META_ENCODE_CV_GAIN %su' % e['fields']['cv_gain'])
    w('#define V_META_ENCODE_CV_ZERO %su' % e['fields']['cv_zero'])
    w('#define V_META_ENCODE_CV_P0 %su' % e['fields']['cv_pair2'][0])
    w('#define V_META_ENCODE_CV_P1 %su' % e['fields']['cv_pair2'][1])
    w('struct v_meta_read { const char *name; uint8_t bytes[0x34]; struct v_meta_fields f; };')
    w('static const struct v_meta_read v_meta_reads[] = {')
    for r in m['read']:
        w('\t{"%s", %s, %s},' % (r['name'], carr(hx(r['bytes'])), fields(r['fields'])))
    w('};')
    w('struct v_meta_write { const char *name; uint8_t before[0x34]; int factory_mode; struct v_meta_fields cur; uint8_t after[0x34]; };')
    w('static const struct v_meta_write v_meta_writes[] = {')
    for r in m['write']:
        w('\t{"%s", %s, %d, %s, %s},' % (r['name'], carr(hx(r['before'])), int(r['factory_mode']),
                                         fields(r['current']), carr(hx(r['after']))))
    w('};')
    w('struct v_setmeta { const char *name; int factory_mode, option; const char *serial, *sku, *factory;')
    w('\tint writes; struct v_meta_fields result; };')
    w('static const struct v_setmeta v_setmetas[] = {')
    for r in m['set_metadata']:
        q = r['request']
        w('\t{"%s", %d, %d, %s, %s, %s, %d, %s},' % (
            r['name'], int(r['factory_mode']), int(r['option']), cstr(q.get('serial')),
            cstr(q.get('sku_variant')), cstr(q.get('factory')), int(r['writes']), fields(r['result'])))
    w('};')
    w('struct v_m6 { uint16_t sw[4]; int writes; };')
    w('static const struct v_m6 v_m6[] = {')
    for r in m['m6']['cases']:
        w('\t{{%s}, %d},' % (', '.join(map(str, r['sw_version'])), int(r['writes'])))
    w('};')
    w('')

    t = js('rtc.json')
    w('/* rtc.json */')
    w('struct v_rtc { unsigned y, mo, d, h, mi, s; uint32_t days; uint32_t clk; };')
    w('static const struct v_rtc v_rtc_encode[] = {')
    for r in t['encode']:
        date, time = r['datetime'].split()
        y, mo, dd = map(int, date.split('-'))
        h, mi, s = map(int, time.split(':'))
        w('\t{%d, %d, %d, %d, %d, %d, %d, %s},' % (y, mo, dd, h, mi, s, r['days'], r['clk']))
    w('};')
    w('struct v_rtc_dec { uint32_t days; unsigned y, mo, d; };')
    w('static const struct v_rtc_dec v_rtc_decode[] = {')
    for r in t['decode']:
        y, mo, dd = map(int, r['date'].split('-'))
        w('\t{%d, %d, %d, %d},' % (r['days'], y, mo, dd))
    w('};')
    w('')

    m = js('metadata_1f.json')
    w('/* metadata_1f.json: the OP-1F record of 0x28 bytes */')
    w('#define V_META1F_SIZE %su' % m['size'])
    e = m['encode'][0]
    w('static const uint8_t v_meta1f_encode_bytes[] = %s;' % carr(hx(e['bytes'])))
    w('static const struct v_meta_fields v_meta1f_encode_fields = %s;' % fields(e['fields']))
    w('struct v_meta1f_read { const char *name; uint8_t bytes[0x28]; struct v_meta_fields f; };')
    w('static const struct v_meta1f_read v_meta1f_reads[] = {')
    for r in m['read']:
        w('\t{"%s", %s, %s},' % (r['name'], carr(hx(r['bytes'])), fields(r['fields'])))
    w('};')
    w('struct v_meta1f_write { const char *name; uint8_t before[0x28]; int factory_mode; struct v_meta_fields cur; uint8_t after[0x28]; };')
    w('static const struct v_meta1f_write v_meta1f_writes[] = {')
    for r in m['write']:
        w('\t{"%s", %s, %d, %s, %s},' % (r['name'], carr(hx(r['before'])), int(r['factory_mode']),
                                         fields(r['current']), carr(hx(r['after']))))
    w('};')
    w('static const struct v_setmeta v_meta1f_setmetas[] = {')
    for r in m['set_metadata']:
        q = r['request']
        w('\t{"%s", %d, %d, %s, %s, %s, %d, %s},' % (
            r['name'], int(r['factory_mode']), int(r['option']), cstr(q.get('serial')),
            cstr(q.get('sku_variant')), cstr(q.get('factory')), int(r['writes']), fields(r['result'])))
    w('};')
    w('')

    p = js('psoc_status_1f.json')
    w('/* psoc_status_1f.json reports */')
    w('struct v_msg { uint8_t id; uint8_t len; uint8_t payload[4]; };')
    for name, rep in p['reports'].items():
        w('static const struct v_msg v_psoc1f_%s[] = {' % name)
        for msg in rep['messages']:
            b = hx(msg['payload'])
            w('\t{%s, %d, %s},' % (msg['id'], len(b), carr(b + bytes(4 - len(b)))))
        w('};')
    w('')

    p = js('psoc_status.json')
    w('/* psoc_status.json reports */')
    for name, rep in p['reports'].items():
        w('static const struct v_msg v_psoc_%s[] = {' % name)
        for msg in rep['messages']:
            b = hx(msg['payload'])
            w('\t{%s, %d, %s},' % (msg['id'], len(b), carr(b + bytes(4 - len(b)))))
        w('};')
    w('')
    w('#endif /* S04_VECTORS_H */')
    genout.write(OUT, '\n'.join(out) + '\n')
    genout.finish()
    return 0


if __name__ == '__main__':
    sys.exit(main())
