"""Generate s03_vectors.h from tests/oracle/S-03-emmc/vectors.

Run from the repository root:  python3 -I -B tests/vectors/s03/gen_s03_vectors.py --out DIR
Image contents are not carried: the C tests build the same eMMC states from
the state names with their own seeded images, so CRCs and hashes are theirs.
"""
import json
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import genout  # noqa: E402  (before anything the generator reads)

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
VEC = os.path.join(ROOT, 'tests', 'oracle', 'S-03-emmc', 'vectors')
OUT = 's03_vectors.h'

LOAD_STATES = ['erased', 'good', 'good512', 'inactive_good', 'bad_crc', 'zero_length', 'too_long',
               'past_partition', 'pad_garbage', 'active_ff', 'enc_f3', 'enc_f2', 'f0_enc_byte',
               'partition_full', 'written_plain', 'format4', 'format_max']
EXPECT = ['no_os', 'BP1', 'BP2']
REASONS = ['', 'no_active', 'zero_length', 'too_long', 'past_partition', 'format', 'encrypted',
           'crc_mismatch']
STARTS = ['p1_active', 'p1_inactive_p2_active', 'both_active', 'neither', 'p1_bad']
BOOTS = ['old', 'new', 'none']
FAILS = [None, 'select1', 'read_header1', 'select2', 'erase', 'write_image', 'read_image',
         'write_header', 'read_header', 'write_header_active', 'read_header_active', 'select_other',
         'read_other', 'deactivate', 'erase_other', 'select0', 'flush_image', 'flush_header',
         'flush_final']


def load(name):
    with open(os.path.join(VEC, name)) as f:
        return json.load(f)


def carr(b):
    return '{' + ', '.join('0x%02x' % c for c in b) + '}'


def op(o):
    if o[0] == 'flush':                         # as the fake eMMC logs it: a switch of EXT_CSD[32] to 1
        return "{'x', 0, 32, 1, %d}" % int(o[-1] == 'error')
    kind = o[0][0]
    err = int(o[-1] == 'error')
    nums = [x for x in o[1:] if x != 'error']
    nums += [0] * (3 - len(nums))
    return "{'%s', %d, %d, %d, %d}" % (kind, nums[0], nums[1], nums[2], err)


def boots_mask(lst):
    m = 0
    for b in lst:
        m |= 1 << BOOTS.index(b)
    return m


def main():
    out = []
    w = out.append
    w('/* SPDX-License-Identifier: GPL-2.0-or-later */')
    w('/* Generated by tests/vectors/s03/gen_s03_vectors.py from tests/oracle/S-03-emmc/vectors. Do not edit. */')
    w('#ifndef S03_VECTORS_H')
    w('#define S03_VECTORS_H')
    w('#include <stdint.h>')
    w('')

    h = load('headers.json')
    w('/* headers.json: mode 0 plain, 1 encrypted, 2 refused */')
    w('struct v_hdr { const char *name; uint8_t raw[16]; uint8_t reserved_ff; uint32_t format, length, crc; int active, mode; };')
    w('static const struct v_hdr v_headers[] = {')
    for r in h['vectors']:
        raw = bytes.fromhex(r['hex'])
        e = r['expect']
        w('\t{"%s", %s, %d, %d, %d, %d, %d, %d},' % (
            r['name'], carr(raw[:16]), int(raw[0x0E:] == b'\xff' * (512 - 0x0E)),
            e['format'], e['length'], e['crc'], int(e['active']),
            ['plain', 'encrypted', 'refused'].index(e['mode'])))
        assert raw[0x0E:] in (bytes(512 - 0x0E), b'\xff' * (512 - 0x0E))
    w('};')
    w('')

    lt = load('load_table.json')
    w('#define V_B %du' % lt['B'])
    w('/* load_table.json: states index v_load_states; expect 0 no_os 1 BP1 2 BP2 */')
    w('static const char *const v_load_states[] = {%s};' % ', '.join('"%s"' % s for s in LOAD_STATES))
    w('struct v_load { uint8_t p1, p2; uint8_t h1[16], h2[16]; int expect, reason;')
    w('\tuint8_t selects[3]; unsigned nselects; uint8_t reads[2]; unsigned nreads;')
    w('\tuint32_t ext_first, ext_last; uint32_t loaded_length; };')
    w('static const struct v_load v_loads[] = {')
    for r in lt['rows']:
        ext = r['extent'] or [0, 0]
        sel = r['selects'] + [0] * (3 - len(r['selects']))
        rd = r['header_reads'] + [0] * (2 - len(r['header_reads']))
        w('\t{%d, %d, %s, %s, %d, %d, {%s}, %d, {%s}, %d, %d, %d, %d},' % (
            LOAD_STATES.index(r['p1']), LOAD_STATES.index(r['p2']),
            carr(bytes.fromhex(r['p1_header'])), carr(bytes.fromhex(r['p2_header'])),
            EXPECT.index(r['expect']), REASONS.index(r['reason']),
            ', '.join(map(str, sel)), len(r['selects']), ', '.join(map(str, rd)), len(r['header_reads']),
            ext[0], ext[1], r['loaded_length']))
    w('};')
    w('')

    ws = load('write_sequences.json')
    assert ws['B'] == lt['B']
    w('/* write_sequences.json.  op: kind s/r/e/w/x (a flush), part, a, b, error.  boots 0 old 1 new 2 none;')
    w(' * torn: a mask of the boots allowed.  fail indexes v_fails. */')
    w('static const char *const v_fails[] = {%s};' % ', '.join(
        'NULL' if f is None else '"%s"' % f for f in FAILS))
    w('static const char *const v_starts[] = {%s};' % ', '.join('"%s"' % s for s in STARTS))
    w('struct v_eop { char kind; unsigned part; uint32_t a, b; int error; };')
    w('struct v_cut { int boots; int torn_mask; };')
    for i, c in enumerate(ws['cases']):
        w('static const struct v_eop v_wops_%d[] = {%s};' % (i, ', '.join(op(o) for o in c['ops']) or '{0, 0, 0, 0, 0}'))
        cuts = c.get('cuts', [])
        torn = {t['op_index']: t for t in c.get('torn', [])}
        items = []
        for k, cut in enumerate(cuts, 1):
            tm = boots_mask(torn[k]['boots']) if k in torn else 0
            items.append('{%d, %d}' % (BOOTS.index(cut['boots']), tm))
        w('static const struct v_cut v_wcuts_%d[] = {%s};' % (i, ', '.join(items) or '{0, 0}'))
    w('struct v_wcase { const char *name; int start; uint32_t length; int corrupt_sector; int corrupt_header;')
    w('\tint fail; int result; unsigned target; uint32_t last_writable; uint8_t header[16];')
    w('\tint final_p1, final_p2, final_boots, boots_before; const struct v_eop *ops; unsigned nops;')
    w('\tconst struct v_cut *cuts; unsigned ncuts; int has_torn; };')
    w('static const struct v_wcase v_wcases[] = {')
    for i, c in enumerate(ws['cases']):
        fin = c.get('final', {})
        ch = {None: 0, 'inactive': 1, 'active': 2}[c['corrupt_header']]
        w('\t{"%s", %d, %d, %d, %d, %d, %d, %d, %d, %s, %d, %d, %d, %d, v_wops_%d, %d, v_wcuts_%d, %d, %d},' % (
            c['name'], STARTS.index(c['start']), c['length'],
            -1 if c['corrupt_sector'] is None else c['corrupt_sector'], ch,
            FAILS.index(c['fail']),
            ['ok', 'refused', 'failed'].index(c['result']), c['target'] or 0,
            c.get('last_writable_sector', 0), carr(bytes.fromhex(c.get('header', '00' * 16))),
            int(fin.get('p1_active', False)), int(fin.get('p2_active', False)),
            BOOTS.index(fin['boots']) if fin else 0, BOOTS.index(c['boots_before']),
            i, len(c['ops']), i, len(c.get('cuts', [])), int('torn' in c)))
    w('};')
    w('')

    ua = load('user_area.json')
    w('/* user_area.json */')
    emmc = ua['emmc']
    w('#define V_EMMC_SECTORS %du' % emmc['sectors'])
    w('#define V_EMMC_GROUP %du' % emmc['erase_group_sectors'])
    w('struct v_emmc { uint32_t sectors, group, opt; };')
    w('static const struct v_emmc v_emmc_refused[] = {%s};' % ', '.join(
        '{%d, %d, %d}' % (r['sectors'], r['erase_group_sectors'], r['opt_write']) for r in emmc['refused']))
    w('static const uint32_t v_opt_ok[] = {%s};' % ', '.join(map(str, emmc['accepted_opt_write'])))
    w('struct v_region { int region; uint32_t first, last; };')
    regions = ['yaffs2', 'unused', 'fat']
    w('static const struct v_region v_map[] = {%s};' % ', '.join(
        '{%d, %d, %d}' % (regions.index(r['region']), r['first'], r['last']) for r in ua['map']))
    w('struct v_fat { uint32_t volume, user; };')
    w('static const struct v_fat v_fat_map[] = {%s};' % ', '.join(
        '{%d, %d}' % (r['volume_sector'], r['user_sector']) for r in ua['fat_map']))
    y = ua['yaffs2']
    w('#define V_YAFFS2_LAST_BLOCK %du' % y['last_block'])
    w('#define V_YAFFS2_BLOCK %du' % y['sectors_per_block'])
    w('#define V_YAFFS2_CHUNK %du' % y['sectors_per_chunk'])
    f = ua['factory_reset_erase']
    w('#define V_FR_GROUP %du' % f['group'])
    w('#define V_FR_FIRST %du' % f['first'])
    w('#define V_FR_LAST %du' % f['last'])
    w('')
    sel = load('select_1f.json')
    w('/* select_1f.json (S-03.012): cmd6 -1 for none */')
    w('struct v_select_1f { uint8_t before; unsigned part; int cmd6; uint8_t after; };')
    w('static const struct v_select_1f v_select_1f[] = {')
    for r in sel['rows']:
        w('\t{%s, %d, %s, %s},' % (r['before'], r['part'], '-1' if r['cmd6'] is None else r['cmd6'],
                                   r['after']))
    w('};')
    w('')
    w('#endif /* S03_VECTORS_H */')
    genout.write(OUT, '\n'.join(out) + '\n')
    genout.finish()
    return 0


if __name__ == '__main__':
    sys.exit(main())
