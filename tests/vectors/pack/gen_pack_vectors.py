"""Generate pack_vectors.h: packed blocks (waffle/boot/pack.h) written by tools/mkldr.py's pack(), for the
stub's unpack test (tests/unit/test_stub_unpack.c).

Run from the repository root:  python3 -I -B tests/vectors/pack/gen_pack_vectors.py --out DIR

Two runs laid out as the image's are: one in the L2 handover reserve, one in DDR, each of code-like
bytes from a fixed generator (some repeats, some noise), and the block's entry. Then the same block
with --spoil's out_crc, and a block of one run of zeros, which deflate takes to a few bytes.
"""
import os
import random
import sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import genout  # noqa: E402  (before anything the generator reads)

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import mkldr  # noqa: E402

OUT = 'pack_vectors.h'
ENTRY = 0x11A00000


def body(rng, n):
    """Bytes that compress about as code does: words from a small set, with noise."""
    words = [rng.getrandbits(32).to_bytes(4, 'little') for _ in range(64)]
    out = bytearray()
    while len(out) < n:
        out += words[rng.randrange(len(words))] if rng.random() < 0.7 else \
            rng.getrandbits(32).to_bytes(4, 'little')
    return bytes(out[:n])


def c_bytes(name, b):
    lines = ['static const uint8_t %s[%d] = {' % (name, max(len(b), 1))]
    for i in range(0, len(b), 16):
        lines.append('\t' + ', '.join('0x%02x' % x for x in b[i:i + 16]) + ',')
    return lines + ['};']


def main():
    rng = random.Random(0x5742504B)
    runs = [(0x0803D000, body(rng, 2276)), (0x8803D000, body(rng, 40000))]
    good = mkldr.pack(runs, ENTRY)
    spoiled = mkldr.pack(runs, ENTRY, spoil=True)
    zeros = mkldr.pack([(0x88100000, bytes(65536))], ENTRY)
    assert mkldr.unpack(good) == (ENTRY, runs)
    lines = ['/* SPDX-License-Identifier: GPL-2.0-or-later */',
             '/* Generated by tests/vectors/pack/gen_pack_vectors.py with tools/mkldr.py\'s',
             ' * pack(). Do not edit. */',
             '#ifndef PACK_VECTORS_H', '#define PACK_VECTORS_H', '',
             '#include <stdint.h>', '',
             '#define PACKV_ENTRY 0x%08xu' % ENTRY,
             '#define PACKV_RUNS %d' % len(runs)]
    for i, (a, b) in enumerate(runs):
        lines.append('#define PACKV_RUN%d_ADDR 0x%08xu' % (i, a))
        lines.append('#define PACKV_RUN%d_LEN %du' % (i, len(b)))
    lines.append('#define PACKV_ZEROS_ADDR 0x88100000u')
    lines.append('#define PACKV_ZEROS_LEN 65536u')
    lines.append('')
    for i, (_, b) in enumerate(runs):
        lines += c_bytes('packv_run%d' % i, b)
    lines += c_bytes('packv_good', good)
    lines += c_bytes('packv_spoiled', spoiled)
    lines += c_bytes('packv_zeros', zeros)
    lines += ['', '#endif /* PACK_VECTORS_H */', '']
    genout.write(OUT, '\n'.join(lines))
    genout.finish()


if __name__ == '__main__':
    main()
