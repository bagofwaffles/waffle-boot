"""Generate s17_vectors.h from tests/oracle/S-17-revisions/vectors/.

Run from the repository root:  python3 -I -B tests/vectors/s17/gen_s17_vectors.py --out DIR
"""
import json
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import genout  # noqa: E402  (before anything the generator reads)

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
VEC = os.path.join(ROOT, 'tests', 'oracle', 'S-17-revisions', 'vectors')
OUT = 's17_vectors.h'


def load(name):
    with open(os.path.join(VEC, name)) as f:
        return json.load(f)


def c_str(s):
    """A C string literal; every byte outside printable ASCII as an octal escape."""
    if s is None:
        return 'NULL'
    out = []
    for b in s.encode('latin-1'):
        c = chr(b)
        if c in '"\\' or not 0x20 <= b < 0x7F or c == '?':
            out.append('\\%03o' % b)
        else:
            out.append(c)
    return '"' + ''.join(out) + '"'


def main():
    lines = ['/* SPDX-License-Identifier: GPL-2.0-or-later */',
             '/* Generated by tests/vectors/s17/gen_s17_vectors.py from',
             ' * tests/oracle/S-17-revisions/vectors/. Do not edit. */',
             '#ifndef S17_VECTORS_H', '#define S17_VECTORS_H', '',
             '#include <stddef.h>', '#include <stdint.h>', '']

    # revision_matrix.json: S-17.001, S-17.003, S-17.004
    rows = load('revision_matrix.json')['rows']
    lines.append('struct s17v_matrix { int master; unsigned pa8, pa0; unsigned decoded; '
                 'int panel; /* -1 none, 0 release, 1 handshake/pulse */ int reported; };')
    lines.append('static const struct s17v_matrix s17v_matrix[] = {')
    for r in rows:
        panel = {'bootloader_release': 0, 'handshake_or_pulse': 1, None: -1}[r['panel_reset']]
        rep = -1 if r['reported_before_greeting'] is None else r['reported_before_greeting']
        lines.append('\t{ %d, %d, %d, %d, %d, %d },' % (r['role'] == 'master', r['pa8'], r['pa0'],
                                                       r['decoded'], panel, rep))
    lines += ['};', '']

    # hw_rev_sequences.json: S-17.010-S-17.015
    seqs = load('hw_rev_sequences.json')
    kinds = {'power_on': 'S17V_POWER_ON', 'metadata_read': 'S17V_META_READ',
             'metadata_read_failed': 'S17V_META_FAILED', 'greeting': 'S17V_GREETING', 'info': 'S17V_INFO'}
    lines.append('enum s17v_kind { S17V_POWER_ON, S17V_META_READ, S17V_META_FAILED, S17V_GREETING, '
                 'S17V_INFO, S17V_END };')
    lines.append('/* POWER_ON: a = pa8, b = pa0. META_FAILED: a = 1 record, 0 serial.')
    lines.append(' * GREETING: len, data. INFO: the expected entry. */')
    lines.append('struct s17v_event { enum s17v_kind kind; unsigned a, b; size_t len; '
                 'uint8_t data[8]; const char *entry; };')
    def emit(seq_list, prefix):
        names = []
        for s in seq_list:
            ident = prefix + s['name']
            names.append((s['name'], ident))
            lines.append('static const struct s17v_event %s[] = {' % ident)
            infos = iter(s['info_entries'])
            for ev in s['events']:
                k = ev[0]
                if k == 'power_on':
                    pa = (ev[1], ev[2]) if len(ev) > 1 else (0, 0)   # no strap sample: S-17.016
                    lines.append('\t{ S17V_POWER_ON, %d, %d, 0, { 0 }, NULL },' % pa)
                elif k == 'metadata_read':
                    lines.append('\t{ S17V_META_READ, 0, 0, 0, { 0 }, NULL },')
                elif k == 'metadata_read_failed':
                    lines.append('\t{ S17V_META_FAILED, %d, 0, 0, { 0 }, NULL },' % (ev[1] == 'record'))
                elif k == 'greeting':
                    p = ev[1]
                    assert len(p) <= 8
                    data = ', '.join('0x%02x' % b for b in p) or '0'
                    lines.append('\t{ S17V_GREETING, 0, 0, %d, { %s }, NULL },' % (len(p), data))
                elif k == 'info':
                    lines.append('\t{ S17V_INFO, 0, 0, 0, { 0 }, %s },' % c_str(next(infos)))
                else:
                    raise ValueError(k)
            lines.append('\t{ S17V_END, 0, 0, 0, { 0 }, NULL },')
            lines.append('};')
        return names

    names = emit(seqs['sequences'], 's17v_seq_')
    no_strap = emit(seqs.get('no_strap_sequences', []), 's17v_nostrap_')
    lines.append('struct s17v_seq { const char *name; const struct s17v_event *ev; };')
    lines.append('static const struct s17v_seq s17v_seqs[] = {')
    lines += ['\t{ %s, %s },' % (c_str(n), i) for n, i in names]
    lines += ['};', '']
    lines.append('/* no_strap_sequences: S-17.016, a device without straps */')
    lines.append('static const struct s17v_seq s17v_nostrap_seqs[] = {')
    lines += ['\t{ %s, %s },' % (c_str(n), i) for n, i in no_strap]
    lines += ['};', '']
    lines.append('struct s17v_log { unsigned byte; const char *hex; };')
    lines.append('static const struct s17v_log s17v_logs[] = {')
    lines += ['\t{ %d, %s },' % (b, c_str(h)) for b, h in seqs['backplane_log']]
    lines += ['};', '']

    # version_reports.json: S-17.020-S-17.024, S-17.032, S-17.034
    vr = load('version_reports.json')
    lines.append('struct s17v_value { const char *text; const char *version; };')
    lines.append('static const struct s17v_value s17v_values[] = {')
    lines += ['\t{ %s, %s },' % (c_str(t), c_str(v)) for t, v in vr['values']]
    lines += ['};', '']

    def state(d):
        return '{ %s, %s, %s, %s }' % (c_str(d['psoc_version']), c_str(d['psoc_serial']),
                                       c_str(d['nordic_app']), c_str(d['nordic_bl']))

    lines.append('struct s17v_state { const char *psoc, *serial, *nordic_app, *nordic_bl; };')
    lines.append('static const struct s17v_state s17v_initial = %s;' % state(vr['initial']))
    lines.append('/* step 1: peer 0 Nordic, 1 PSoC; step 2: mode_reply then payload */')
    lines.append('struct s17v_reply { const char *name; int step; int peer; const char *mode_reply; '
                 'const char *payload; struct s17v_state before, after; };')
    lines.append('static const struct s17v_reply s17v_replies[] = {')
    for r in vr['replies']:
        peer = {'nordic': 0, 'psoc': 1}.get(r.get('peer'), -1)
        lines.append('\t{ %s, %d, %d, %s, %s, %s, %s },' % (
            c_str(r['name']), r['step'], peer, c_str(r.get('mode_reply')), c_str(r['payload']),
            state(r['before']), state(r['after'])))
    lines += ['};', '']
    lines.append('struct s17v_run_end { const char *name; struct s17v_state before; '
                 'const char *s11_nordic_app; const char *nordic_reply, *psoc_reply; '
                 'struct s17v_state after; };')
    lines.append('static const struct s17v_run_end s17v_run_ends[] = {')
    for r in vr['run_end']:
        assert set(r['s11_sets']) <= {'nordic_app'}
        lines.append('\t{ %s, %s, %s, %s, %s, %s },' % (
            c_str(r['name']), state(r['before']), c_str(r['s11_sets'].get('nordic_app')),
            c_str(r['nordic_reply']), c_str(r['psoc_reply']), state(r['after'])))
    lines += ['};', '']
    ov = vr['own_version']
    lines.append('static const char *const s17v_own_accept[] = { %s };' %
                 ', '.join(c_str(s) for s in ov['accept']))
    lines.append('static const char *const s17v_own_reject[] = { %s };' %
                 ', '.join(c_str(s) for s in ov['reject']))
    lines.append('')

    # supported.json: S-17.042
    sup = load('supported.json')
    lines.append('static const char *const s17v_copro_versions[] = { %s };' %
                 ', '.join(c_str(c['version']) for c in sup['coprocessors']))
    lines += ['', '#endif /* S17_VECTORS_H */', '']

    genout.write(OUT, '\n'.join(lines))
    genout.finish()


if __name__ == '__main__':
    sys.exit(main())
