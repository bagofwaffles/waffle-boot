"""Turns tests/oracle/S-14-logging/vectors/ into s14_vectors.h for the C unit tests.

    python3 -I -B tests/vectors/s14/gen_s14_vectors.py --out DIR  # write DIR/s14_vectors.h

Run from the repository root. Standard library only. The header holds the same cases as the JSON files,
as C data, in sections a test selects by defining S14V_LINES, S14V_LOG or S14V_EXPORT; nothing is added
or computed beyond splitting a frame's line into its tag and text."""
import json
import os
import re
import sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import genout  # noqa: E402  (before anything the generator reads)

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
SRC = os.path.join(ROOT, 'tests', 'oracle', 'S-14-logging', 'vectors')
OUT = 's14_vectors.h'

TAG_RE = re.compile(rb'([a-z0-9_-]{0,16})\[((?:[1-9][0-9]{0,9})?)\]: ')


def load(name):
    with open(os.path.join(SRC, name)) as f:
        return json.load(f)


def cbytes(b):
    """A C string literal holding the bytes b: printable ASCII as itself, the rest as three-digit octal
    escapes (never ambiguous with a following digit); '?' escaped against trigraphs."""
    out = []
    for c in b:
        ch = chr(c)
        if ch in '"\\?':
            out.append('\\' + ch)
        elif 0x20 <= c <= 0x7E:
            out.append(ch)
        else:
            out.append('\\%03o' % c)
    return '"' + ''.join(out) + '"'


def cstr(s):
    if s is None:
        return 'NULL'
    return cbytes(s.encode('utf-8'))


def cbool(v):
    return 'true' if v else 'false'


def gen():
    o = []
    w = o.append
    w('/* SPDX-License-Identifier: GPL-2.0-or-later */')
    w('/* Generated by tests/vectors/s14/gen_s14_vectors.py from tests/oracle/S-14-logging/vectors/. Do not edit. */')
    w('#ifndef S14_VECTORS_H')
    w('#define S14_VECTORS_H')
    w('')
    w('#include <stdbool.h>')
    w('#include <stddef.h>')
    w('#include <stdint.h>')
    w('')

    # lines.json: S-14.001, S-14.002, S-14.004, S-14.006, S-14.007
    v = load('lines.json')
    w('#ifdef S14V_LINES')
    w('struct s14v_line {')
    w('\tconst char *group, *note;')
    w('\tuint32_t timestamp;     /* taken mod 2^32 */')
    w('\tconst char *name;       /* NULL: no tag */')
    w('\tuint32_t line_no;       /* 0: empty number */')
    w('\tconst char *text; size_t text_len;')
    w('\tsize_t full_length;')
    w('\tconst char *line; size_t line_len;')
    w('};')
    w('static const struct s14v_line s14v_lines[] = {')
    for c in v['lines']:
        text = bytes.fromhex(c['text'])
        line = bytes.fromhex(c['line'])
        w('\t{ %s, %s, 0x%08xu, %s, %du, %s, %du, %du, %s, %du },' % (
            cstr(c['group']), cstr(c['note']), c['timestamp'] % (1 << 32), cstr(c['name']),
            c['line_no'] or 0, cbytes(text), len(text), c['full_length'], cbytes(line), len(line)))
    w('};')
    w('struct s14v_tag { const char *body; size_t body_len; bool tagged; size_t tag_len; };')
    w('static const struct s14v_tag s14v_tags[] = {')
    for c in v['tags']:
        body = bytes.fromhex(c['body'])
        tl = len(body) - len(bytes.fromhex(c['text'])) if c['tagged'] else 0
        w('\t{ %s, %du, %s, %du },' % (cbytes(body), len(body), cbool(c['tagged']), tl))
    w('};')
    w('#endif')
    w('')

    # log_config.json: S-14.011, S-14.012, S-14.013
    v = load('log_config.json')
    w('#ifdef S14V_LOG')
    ini = v['initial']
    w('struct s14v_state { unsigned threshold; bool psoc, cdc; };')
    w('static const struct s14v_state s14v_initial = { %du, %s, %s };' % (
        ini['threshold'], cbool(ini['psoc']), cbool(ini['cdc'])))
    w('struct s14v_request { const char *payload; size_t len; struct s14v_state before, after; const char *note; };')
    w('static const struct s14v_request s14v_requests[] = {')
    for r in v['requests']:
        p = bytes.fromhex(r['payload'])
        b, a = r['before'], r['after']
        w('\t{ %s, %du, { %du, %s, %s }, { %du, %s, %s }, %s },' % (
            cbytes(p), len(p), b['threshold'], cbool(b['psoc']), cbool(b['cdc']),
            a['threshold'], cbool(a['psoc']), cbool(a['cdc']), cstr(r['note'])))
    w('};')
    w('struct s14v_filter { unsigned level, threshold; bool emitted; };')
    w('static const struct s14v_filter s14v_filter[] = {')
    for f in v['filter']:
        w('\t{ %du, %du, %s },' % (f['level'], f['threshold'], cbool(f['emitted'])))
    w('};')
    w('')

    # frames.json: S-14.010, S-14.021, S-14.023
    v = load('frames.json')
    w('struct s14v_frame {')
    w('\tbool cdc; unsigned level; unsigned seq; unsigned route; unsigned id;')
    w('\tuint32_t timestamp; const char *name; uint32_t line_no;')
    w('\tconst char *text; size_t text_len;')
    w('\tconst char *line; size_t line_len;')
    w('};')
    w('static const struct s14v_frame s14v_frames[] = {')
    for f in v['frames']:
        line = bytes.fromhex(f['line'])
        m = TAG_RE.match(line[4:])
        assert m, f
        name, num, text = m.group(1).decode(), int(m.group(2) or 0), line[4 + m.end():]
        if len(line) == 248 and line.endswith(b'..'):
            text = b'x' * 300                     # the 'longest line' case: built from 300 x's, cut
        w('\t{ %s, %du, %du, 0x%02xu, 0x%02xu, 0x%08xu, %s, %du, %s, %du, %s, %du },' % (
            cbool(f['sink'] == 'cdc'), f['level'], f['seq'], f['route'], f['id'],
            int.from_bytes(line[:4], 'big'), cstr(name), num, cbytes(text), len(text),
            cbytes(line), len(line)))
    w('};')
    w('')

    # relay.json: S-14.008, S-14.040, S-14.041, S-14.042
    v = load('relay.json')
    w('struct s14v_relay {')
    w('\tconst char *note; unsigned src, id;')
    w('\tconst char *payload; size_t payload_len;')
    w('\tbool relayed; unsigned level; const char *text; size_t text_len;')
    w('};')
    w('static const struct s14v_relay s14v_relays[] = {')
    for c in v['cases']:
        p = bytes.fromhex(c['payload'])
        t = bytes.fromhex(c['text']) if c['text'] is not None else b''
        w('\t{ %s, %du, 0x%02xu, %s, %du, %s, %du, %s, %du },' % (
            cstr(c['note']), c['src'], c['id'], cbytes(p), len(p), cbool(c['relayed']),
            c['level'] if c['level'] is not None else 0, cbytes(t), len(t)))
    w('};')
    w('#endif')
    w('')

    # export.json: S-14.051, S-14.052
    v = load('export.json')
    w('#ifdef S14V_EXPORT')
    w('#define S14V_EXPORT_LIMIT %du' % v['limit'])
    w('struct s14v_entry { const char *name; bool regular; uint32_t mtime, size; bool fails; };')
    w('struct s14v_export {')
    w('\tconst char *note;')
    w('\tconst struct s14v_entry *entries; size_t n_entries;')
    w('\tconst char *const *copied; size_t n_copied;')
    w('};')
    for i, g in enumerate(v['groups']):
        w('static const struct s14v_entry s14v_export_entries_%d[] = {' % i)
        for e in g['entries']:
            w('\t{ %s, %s, %du, %du, %s },' % (cstr(e['name']), cbool(e['type'] == 'file'), e['mtime'],
                                               e['size'], cbool(e['name'] in g['fails'])))
        w('};')
        w('static const char *const s14v_export_copied_%d[] = { %s };' % (
            i, ', '.join([cstr(n) for n in g['copied']] + ['NULL'])))
    w('static const struct s14v_export s14v_exports[] = {')
    for i, g in enumerate(v['groups']):
        w('\t{ %s, s14v_export_entries_%d, %du, s14v_export_copied_%d, %du },' % (
            cstr(g['note']), i, len(g['entries']), i, len(g['copied'])))
    w('};')
    w('#endif')
    w('')
    w('#define S14V_N(a) (sizeof(a) / sizeof((a)[0]))')
    w('')
    w('#endif /* S14_VECTORS_H */')
    return '\n'.join(o) + '\n'


def main():
    genout.write(OUT, gen())
    genout.finish()
    return 0


if __name__ == '__main__':
    sys.exit(main())
