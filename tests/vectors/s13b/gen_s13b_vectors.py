"""Generate s13b_vectors.h from tests/oracle/S-13b-buses-and-pins/vectors/: the bridge's DMA traces
(bridge_dma.json, S-13b.083), the master's sessions (bridge_sessions.json, S-13b.040), the slave's reply
set-ups (reply_setup.json, S-13b.044) and its reply ends (slave_tx.json, S-13b.045), for the C form of
check.py's check_bridge_dma, check_master_sessions, check_reply_setup and check_slave_tx in
tests/unit/s13b_check.h.

Run from the repository root:  python3 -I -B tests/vectors/s13b/gen_s13b_vectors.py --out DIR
"""
import json
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import genout  # noqa: E402  (before anything the generator reads)

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
VEC = os.path.join(ROOT, 'tests', 'oracle', 'S-13b-buses-and-pins', 'vectors')
OUT = 's13b_vectors.h'


def load(name):
    with open(os.path.join(VEC, name)) as f:
        return json.load(f)


def rules(expect):
    return ' | '.join('S13B_' + r.upper() for r in sorted(set(expect))) or '0'


def main():
    lines = ['/* SPDX-License-Identifier: GPL-2.0-or-later */',
             '/* Generated by tests/vectors/s13b/gen_s13b_vectors.py from',
             ' * tests/oracle/S-13b-buses-and-pins/vectors/. Do not edit. */',
             '#ifndef S13B_VECTORS_H', '#define S13B_VECTORS_H', '',
             '/* Include tests/unit/s13b_check.h first. */', '']

    rows = load('bridge_dma.json')['rows']
    names = []
    for i, r in enumerate(rows):
        ident = 's13bv_dma_%d' % i
        names.append((r, ident))
        lines.append('static const struct s13b_ev %s[] = {' % ident)
        for e in r['trace']:
            if e['op'] == 'ev' and e['ev'] == 'desc':
                lines.append('\t{ S13B_DESC, NULL, 0u, %du, %du, false },' % (e['ch'], sum(e['bytes'])))
            elif e['op'] == 'ev':
                lines.append('\t{ S13B_SELECT, NULL, 0u, 0u, 0u, %s },' % ('true' if e['on'] else 'false'))
            else:
                lines.append('\t{ S13B_%s, "%s", 0x%08Xu, 0u, 0u, false },'
                             % ('W' if e['op'] == 'w' else 'R', e['reg'], e['val']))
        lines += ['};', '']
    lines.append('struct s13bv_dma { const char *name; enum s13b_kind kind; uint32_t words; '
                 'unsigned nparts; uint32_t parts[4]; const struct s13b_ev *trace; size_t n; unsigned expect; };')
    lines.append('static const struct s13bv_dma s13bv_dma[] = {')
    for r, ident in names:
        parts = r.get('parts') or []
        assert len(parts) <= 4
        lines.append('\t{ "%s", S13B_%s, %du, %du, { %s }, %s, sizeof %s / sizeof %s[0], %s },'
                     % (r['name'], r['kind'].upper(), r.get('words') or 0, len(parts),
                        ', '.join('%du' % p for p in parts) or '0', ident, ident, ident, rules(r['expect'])))
    lines += ['};', '']

    rows = load('bridge_sessions.json')['rows']
    names = []
    for i, r in enumerate(rows):
        ident = 's13bv_ses_%d' % i
        names.append((r, ident))
        lines.append('static const struct s13b_sev %s[] = {' % ident)
        for e in r['trace']:
            ev = e['ev']
            if ev == 'en':
                lines.append('\t{ S13B_EV_EN, %s, %d },' % ('true' if e['on'] else 'false',
                                                           e['miom'] if 'miom' in e else -1))
            elif ev == 'select':
                lines.append('\t{ S13B_EV_SELECT, %s, -1 },' % ('true' if e['on'] else 'false'))
            elif ev == 'word':
                lines.append('\t{ S13B_EV_WORD, false, -1 },')
            else:
                lines.append('\t{ S13B_EV_SETUP, false, -1 },')
        lines += ['};', '']
    lines.append('struct s13bv_ses { const char *name; const struct s13b_sev *trace; size_t n; unsigned expect; };')
    lines.append('static const struct s13bv_ses s13bv_ses[] = {')
    for r, ident in names:
        lines.append('\t{ "%s", %s, sizeof %s / sizeof %s[0], %s },'
                     % (r['name'], ident, ident, ident, rules(r['expect'])))
    lines += ['};', '']

    # check_reply_setup (S-13b.044)
    steps = {'stat': 'STAT', 'feed': 'FEED', 'twc': 'TWC', 'txctl': 'TXCTL', 'rxctl': 'RXCTL', 'en': 'EN',
             'dma': 'DMA', 'dma_done': 'DMA_DONE', 'tf_unmask': 'TF_UNMASK'}
    links = {'pre': 'PRE', 'post': 'POST', 'quad': 'QUAD'}
    rows = load('reply_setup.json')['rows']
    for i, r in enumerate(rows):
        if r['setup'].get('order') is not None:
            lines.append('static const enum s13b_step s13bv_order_%d[] = { %s };'
                         % (i, ', '.join('S13B_ST_' + steps[x] for x in r['setup']['order'])))
    lines.append('struct s13bv_setup { const char *name; struct s13b_reply_setup s; unsigned expect; };')
    lines.append('static const struct s13bv_setup s13bv_setup[] = {')
    for i, r in enumerate(rows):
        s = r['setup']
        assert s.get('end') is None
        order = s.get('order')
        lines.append('\t{ "%s", { S13B_LINK_%s, 0x%Xu, 0x%Xu, 0x%Xu, %du, %du, %du, false, %s, %d }, %s },'
                     % (r['name'], links[s['link']], s['ctl'], s['txctl'], s['rxctl'], s['twc'], s['words'],
                        s['queued'], 's13bv_order_%d' % i if order is not None else 'NULL',
                        len(order) if order is not None else 0, rules(r['expect'])))
    lines += ['};', '']

    # check_slave_tx (S-13b.045)
    v = load('slave_tx.json')
    flags = ('tf', 'tur', 'tc', 'ror', 'twc_zero', 'tfifo_empty', 'spif')
    for i, r in enumerate(v['rows']):
        lines.append('static const struct s13b_txe s13bv_tx_%d[] = {' % i)
        for e in r['trace']:
            assert set(e) <= {'ev', 'word', 'rx_words', 'quiet_us', 't_us'} | set(flags), e
            f = ' | '.join('S13B_TXF_' + k.upper() for k in flags if e.get(k)) or '0u'
            lines.append('\t{ S13B_TX_%s, %du, %s, %d, %du, %d },'
                         % (e['ev'].upper(), e.get('word', 0), f, e.get('rx_words', -1), e.get('quiet_us', 0),
                            e.get('t_us', -1)))
        lines += ['};', '']
    lines.append('#define S13BV_TX_WORDS %du' % v['words'])
    lines.append('struct s13bv_tx { const char *name; bool quad; const struct s13b_txe *trace; size_t n; '
                 'unsigned expect; };')
    lines.append('static const struct s13bv_tx s13bv_tx[] = {')
    for i, r in enumerate(v['rows']):
        assert r.get('io', 'single') in ('single', 'quad') and 'end' not in r
        lines.append('\t{ "%s", %s, s13bv_tx_%d, sizeof s13bv_tx_%d / sizeof s13bv_tx_%d[0], %s },'
                     % (r['name'], 'true' if r.get('io') == 'quad' else 'false', i, i, i, rules(r['expect'])))
    lines += ['};', '', '#endif /* S13B_VECTORS_H */', '']
    genout.write(OUT, '\n'.join(lines))
    genout.finish()


if __name__ == '__main__':
    main()
