"""Generate vectors/hostlink_access.json from hostlink_model.py: for each session a host can be in, what
the approval makes of each call and action (S-10c.123, S-10c.127, S-10c.135 - S-10c.137), and APPROVE's
and the pass's outcomes with Developer's item on and off. tests/tools/test_hostlink_tool.py runs them on
src/hostlink.c.

    python3 -I -B tests/oracle/S-10c-host-commands/gen_hostlink.py --write     write the file
    python3 -I -B tests/oracle/S-10c-host-commands/gen_hostlink.py             check it is current
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import hostlink_model as m  # noqa: E402

OUT = os.path.join(HERE, 'vectors', 'hostlink_access.json')

# One request of each call and action: its bytes after call and tag, and the root a path names
REQUESTS = [
    ('SESSION', 0x01, b'', None, None), ('INFO', 0x04, b'', None, None), ('JOB', 0x06, b'\x01', None, None),
    ('SET host link', 0x05, b'\x07\x01', None, None),
    ('STAT /yaffs2', 0x10, b'/yaffs2', 'yaffs2', None), ('STAT /os', 0x10, b'/os', 'os', None),
    ('LIST /yaffs2', 0x11, b'\x00\x00/yaffs2', 'yaffs2', None), ('LIST /os', 0x11, b'\x00\x00/os', 'os', None),
    ('GET', 0x12, b'\x00\x00\x00\x00\x10/yaffs2/lost+found', 'yaffs2', None),
    ('HASH', 0x13, b'/yaffs2/x', 'yaffs2', None),
    ('PUT_OPEN', 0x14, bytes(4) + bytes(32) + b'/yaffs2/x', 'yaffs2', None),
    ('PUT_DATA', 0x15, bytes(4), None, None), ('PUT_END', 0x16, b'', None, None),
    ('REMOVE', 0x17, b'/yaffs2/x', 'yaffs2', None), ('MKDIR', 0x18, b'/yaffs2/x', 'yaffs2', None),
    ('RENAME', 0x19, b'/yaffs2/x\x00/yaffs2/y', 'yaffs2', None),
    ('RAM_OPEN', 0x21, b'\x10\x00\x00\x00' + bytes(32), None, None),
    ('RAM_DATA', 0x22, bytes(4), None, None), ('RAM_END', 0x23, b'', None, None),
    ('RUN install', 0x20, b'\x01\xff/yaffs2/p.tfw', 'yaffs2', 0x01),
    ('RUN OS write', 0x20, b'\x02/yaffs2/os.ldr', 'yaffs2', 0x02),
    ('RUN start once', 0x20, b'\x03', None, 0x03), ('RUN restart', 0x20, b'\x04', None, 0x04),
    ('RUN continue to OS', 0x20, b'\x05', None, 0x05), ('RUN restart into a mode', 0x20, b'\x06\x02', None, 0x06),
    ('RUN RAM start', 0x20, b'\x07', None, 0x07),
    ('RUN factory reset', 0x20, b'\x10', None, 0x10), ('RUN Protected writes', 0x20, b'\x11', None, 0x11),
]
SESSIONS = ['none', 'approved, no hold', 'approved']


def build():
    access = []
    for name, call, args, root, action in REQUESTS:
        cls = m.call_class(call, root, action)
        access.append({'name': name, 'request': bytes([call]).hex() + args.hex(), 'class': cls,
                       'gate': {s: m.gate(s, cls) for s in SESSIONS}})
    approve = [{'session': s, 'no_hold': nh, 'after': m.approve(s, nh)}
               for s in ('none', 'refused', 'timed out', 'approved, no hold', 'approved') for nh in (False, True)]
    poll = [{'session': s, 'no_hold': nh, 'after': m.poll(s, nh)}
            for s in ('approved, no hold', 'approved') for nh in (False, True)]
    return {'about': 'S-10c.123, S-10c.127, S-10c.135 - S-10c.137: generated by gen_hostlink.py',
            'sessions': m.SESSIONS, 'access': access, 'approve': approve, 'poll': poll}


def text():
    d = build()
    d['sessions'] = {str(k): v for k, v in d['sessions'].items()}
    return json.dumps(d, indent=1) + '\n'


def main(argv):
    want = text()
    if '--write' in argv:
        with open(OUT, 'w') as f:
            f.write(want)
        return 0
    try:
        with open(OUT) as f:
            have = f.read()
    except OSError:
        have = None
    if have != want:
        print('%s is not current: run %s --write' % (os.path.relpath(OUT), os.path.basename(__file__)))
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
